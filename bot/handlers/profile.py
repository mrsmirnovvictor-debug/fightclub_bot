@router.message(Command("classes"))
async def cmd_classes(message: Message) -> None:
    blocks = []
    for fclass in FIGHTER_CLASSES.values():
        stats = fclass.base_stats
        blocks.append(
            f"{fclass.label} — <i>{fclass.tagline}</i>\n"
            f"{fclass.description}\n"
            f"Старт: 💪{stats.strength} 🤸{stats.agility} "
            f"🔮{stats.intuition} 🫀{stats.endurance}"
        )
    await message.answer("\n\n".join(blocks))


@router.message(Command("miniapp"))
async def cmd_miniapp(message: Message, config: Config) -> None:
    """Проверка карточки: какая ссылка стоит под именем бойца в чате боя.

    Самая частая поломка не в коде: если в BotFather нет приложения с таким
    коротким именем, Telegram по этой ссылке молча открывает чат с ботом.
    Команда показывает ссылку целиком, чтобы это было видно сразу.
    """
    user_id = message.from_user.id
    lines = ["🔗 <b>Как настроена карточка</b>", ""]

    if links.bot_username:
        lines.append(f"Бот: <code>@{links.bot_username}</code>")
    else:  # pragma: no cover - до первого get_me такого не бывает
        lines.append("Бот: имя ещё не получено")

    if links.miniapp_name:
        lines.append(f"Короткое имя мини-аппа: <code>{esc(links.miniapp_name)}</code>")
    elif links.main_app:
        lines.append("Мини-апп включён главным (MINIAPP_MAIN)")
    else:
        lines.append(
            "Короткого имени нет: имена в чате ведут в личку, "
            "а карточку присылает сам бот"
        )
    lines.append(
        f"Адрес мини-аппа: <code>{esc(config.webapp_url) or '—'}</code>"
    )

    lines += ["", "Под именем бойца в чате стоит:", f"<code>{esc(links.href(user_id))}</code>"]
    if links.card_url(user_id):
        lines += [
            "",
            "Открой её и проверь. Если вместо карточки открылся чат с ботом — "
            "приложения с таким коротким именем в BotFather нет. Лечится одним "
            "из трёх способов: завести его (/newapp) и вписать то же имя в "
            "MINIAPP_NAME; включить мини-апп главным (Configure Mini App) и "
            "поставить MINIAPP_MAIN=1 с пустым MINIAPP_NAME; либо очистить "
            "MINIAPP_NAME — тогда имя в чате ведёт в личку, и бот присылает "
            "карточку сам.",
        ]
    return await message.answer("\n".join(lines), disable_web_page_preview=True)


@router.message(Command("card"))
async def cmd_card(message: Message, db: Database, config: Config) -> None:
    player = await db.get_player(message.from_user.id)
    if player is None:
        await message.answer("Бойца ещё нет. Напиши мне в личку /start.")
        return

    keyboard = card_keyboard(
        config, player.user_id, private=message.chat.type == "private"
    )
    if keyboard is None:
        await message.answer(
            "Карточка пока не поднята: администратор клуба не настроил мини-апп.\n"
            "Вот что есть в текстовом виде:"
        )
        await message.answer(profile_text(player))
        return
    await message.answer(
        f"🪪 Карточка бойца <b>{esc(player.nickname)}</b> "
        f"[{player.level}] — открывается прямо в Telegram.",
        reply_markup=keyboard,
    )


@router.message(Command("profile", "me"))
async def cmd_profile(message: Message, db: Database, config: Config) -> None:
    player = await db.get_player(message.from_user.id)
    if player is None:
        await message.answer("Бойца ещё нет. Напиши мне в личку /start.")
        return
    keyboard = card_keyboard(
        config, player.user_id, private=message.chat.type == "private"
    )
    if message.chat.type == "private":
        await send_profile(message, player, keyboard)
    else:
        await message.answer(profile_text(player), reply_markup=keyboard)


@router.message(Command("top"))
async def cmd_top(message: Message, db: Database) -> None:
    players = await db.top_players(10)
    if not players:
        await message.answer("В клубе пока ни одного бойца. /start — исправь это.")
        return
    medals = {0: "🥇", 1: "🥈", 2: "🥉"}
    lines = ["🏆 <b>Чемпионы клуба</b>", "<i>по рейтингу</i>", ""]
    for index, player in enumerate(players):
        lines.append(
            f"{medals.get(index, f'{index + 1}.')} {player.avatar} "
            f"<b>{player_link(player)}</b> — "
            f"<b>{player.rating}</b> · "
            f"{player.fclass.title}, {player.level} ур. · "
            f"{player.wins}—{player.losses}"
        )
    await message.answer("\n".join(lines))
