"""Полиция: дежурная часть, задержания и тюрьма.

Ограбление дало мафии право брать людей за карман. Эта половина — то,
что город на это отвечает. Без неё мафия была бы стороной без
противника, а служба в полиции — строчкой в трудовой.

**Полиция видит всё.** Каждое нападение в городе попадает в дежурную
часть: кто, кого, где и на сколько. Прятать это не от кого — жертва и
так знает, что её обобрали, а мафия знает, что обобрала.

**Вмешаться может любой.** Полицейский приходит на место драки и
встаёт на сторону того, на кого напали. Лицензии ему для этого не надо:
лицензию покупают, чтобы нападать, а защищать — это работа.

**Деньги полицейского в драке не трогают.** Добыча идёт только из
кармана того, на кого напали, и значит, проигравший патрульный теряет
здоровье, но не кошелёк. Иначе выходить на драку было бы невыгодно, и
никто бы не выходил.

**Заявление даёт ордер.** Жертва приходит в участок и пишет заявление —
и с этой минуты задержать нападавшего может любой сотрудник. Ордер не
на предъявителя и не покупается: он появляется из того, что человек
пожаловался.

**Задержание — та же драка.** Разница в развязке: взятое мафией
возвращается в участок, а сам он едет в тюрьму. Деньги в участке ждут
своего хозяина: жертва приходит и забирает.

**Срок растёт.** Три часа за первый раз, шесть за второй, двенадцать за
третий, сутки за четвёртый и дальше. Из тюрьмы не выходят, пока срок не
кончится, — ни на работу, ни на штурм.

**У полиции есть норма.** Задержали за неделю половину того, что мафия
наворотила, — к копилке добавляется премия, и вся копилка делится между
служащими поровну. Не выполнили — копилка просто копится дальше.

Действия — в `bot.police_service`, драка — в `bot.robbery_service`,
хранение — в `bot.database`, экраны — в `bot.webapp.police`.
"""

from __future__ import annotations

HOUR = 60 * 60

# Сколько часов сидят за первое, второе, третье задержание и за всё
# последующее. Срок растёт, потому что иначе он не наказание, а пошлина
JAIL_TERMS: tuple[int, ...] = (3, 6, 12, 24)

# Где сидят. Это существующий дом города, а не отдельный экран
PRISON = "prison"

# Сколько падает в копилку участка за одно задержание. Платит город, а
# не задержанный: у того забирают только награбленное
ARREST_FEE = 500

# Норма: задержаний должно быть не меньше половины нападений за неделю
QUOTA_SHARE = 0.5
# Премия за выполненную норму. Падает в ту же копилку и делится со всем
# остальным — поровну между теми, кто служит
QUOTA_BONUS = 5_000


def jail_hours(times: int) -> int:
    """Сколько часов сидеть за `times`-е по счёту задержание."""
    if times < 1:
        return 0
    return JAIL_TERMS[min(times, len(JAIL_TERMS)) - 1]


def jail_seconds(times: int) -> int:
    return jail_hours(times) * HOUR


def jail_left(until: int, now: int) -> int:
    """Сколько секунд ещё сидеть. Ноль — свободен."""
    return max(0, until - now)


def quota_target(attacks: int) -> int:
    """Сколько задержаний нужно за неделю при стольких нападениях.

    Округляем вверх: при одном нападении норма — одно задержание, а не
    половина. Половина задержания — это не половина работы, это ноль.
    """
    if attacks <= 0:
        return 0
    return -(-int(attacks * QUOTA_SHARE * 100) // 100)


def quota_done(arrests: int, attacks: int) -> bool:
    """Выполнена ли норма. Нападений не было — считается выполненной."""
    return arrests >= quota_target(attacks)


def shares(pot: int, heads: int) -> list[int]:
    """Разделить копилку поровну. Остаток остаётся в копилке.

    Делим нацело: три кредита на двоих — это по одному и один в кассе,
    а не по полтора. Дробных кредитов в клубе нет нигде.
    """
    if heads <= 0 or pot <= 0:
        return []
    each = pot // heads
    return [each] * heads if each else []


