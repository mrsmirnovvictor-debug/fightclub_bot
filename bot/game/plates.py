"""Номерной знак машины: а000аа и всё, что из него следует.

Номер — это имя машины в городе. До него машина опознавалась парой
«хозяин плюс модель», и этого хватало, пока машину не начали угонять: у
угнанной хозяин как раз меняется, а модель на каждом втором такая же.

**Маска одна на весь город: буква, три цифры, две буквы.** Буквы —
только те двенадцать, что одинаково читаются в кириллице и латинице:
на настоящих знаках так и сделано, и путать «В» с «B» в чате не
придётся.

**Номер уникален.** Два одинаковых знака в городе — это два «того
самого» автомобиля, и проверка полиции перестала бы что-либо значить.
Держит это не проверка в питоне, а уникальный индекс в базе: номер
выдаётся броском, и бросок однажды повторится.

**Номер перебивают.** На автомойке, за деньги: это единственный способ
снять с машины её прошлое — вместе с номером уходит и розыск. Отсюда и
цена, и то, что услуга лежит в мойке, а не в салоне.

Правила тут, хранение — в `bot.database`, перебивка — в
`bot.car_service`.
"""

from __future__ import annotations

import random

# Двенадцать букв, одинаковых в обеих азбуках. Остальные на знаки не
# идут: «Ж» в латинице не написать, а номер должны читать все
LETTERS = "АВЕКМНОРСТУХ"
DIGITS = "0123456789"

# Как это выглядит в объявлении: буква, три цифры, две буквы
MASK = "а000аа"

# Сколько всего номеров бывает: 12 × 1000 × 12 × 12. Миллион семьсот —
# столько, что бросок почти никогда не повторяется, и всё же повторится
TOTAL = len(LETTERS) * 1000 * len(LETTERS) * len(LETTERS)


def random_plate(rng: random.Random | None = None) -> str:
    """Выдать номер по маске. Повтор ловит база, а не этот бросок."""
    roll = rng or random
    return "".join(
        (
            roll.choice(LETTERS),
            "".join(roll.choice(DIGITS) for _ in range(3)),
            roll.choice(LETTERS),
            roll.choice(LETTERS),
        )
    )


def is_plate(text: str) -> bool:
    """Похоже ли это на городской номер."""
    one = (text or "").strip().upper()
    if len(one) != 6:
        return False
    return (
        one[0] in LETTERS
        and all(digit in DIGITS for digit in one[1:4])
        and one[4] in LETTERS
        and one[5] in LETTERS
    )


def pretty(plate: str) -> str:
    """Номер, как его пишут на экране: «А123ВС». Пусто — номера нет."""
    return (plate or "").strip().upper()


