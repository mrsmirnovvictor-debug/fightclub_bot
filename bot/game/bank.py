"""Vegas Банк: счёт, карта и то, чем платят в городе.

До банка у бойца был один кошелёк — наличные, и всякая цена бралась
из него. Банк заводит второй: **счёт**, на котором деньги лежат, и
**карту**, которой с этого счёта платят. Отсюда и всё остальное в этом
файле: два кошелька означают, что у каждой цены есть источник, а у
источника — своя цена.

**Счёт открывается мгновенно и бесплатно, и он один на бойца.** На него
кладут наличные, с него снимают наличные, с него переводят на чужой счёт
по номеру. Ни за одно из этих действий банк не берёт ни кредита: банк в
клубе не зарабатывает на переводах, он зарабатывает на карте.

**Карта стоит сто за выпуск и сто в год за обслуживание, первый год
входит в выпуск.** Карта бессрочна: у неё нет даты окончания, есть
оплаченный год. Кончился оплаченный год — банк списывает следующий со
счёта. Не хватило на счету — карта не закрывается, а перестаёт
обслуживаться: ею нельзя платить, пока долг не погашен. Закрывать карту
за сто кредитов было бы наказанием не по вине: боец мог просто не зайти.

**Год списывается один за подход, а не за все пропущенные.** То же
правило, что у страхового полиса: клуб берёт деньги за услугу, а не за
время, в которое к услуге не приходили. Боец, вернувшийся через три года,
увидит одно списание.

**Счёт без карты в магазинах не работает.** Платят картой, а не счётом:
счёт — это место, где деньги лежат, карта — то, чем их оттуда достают.
Поэтому «оплатить со счёта» без карты нельзя, а снять наличные — можно.

**Скидка живёт на карте и зависит от места.** Она не бонус за покупку, а
цена, назначенная банком: выбрал карту — увидел свою цену, выбрал
наличные — цену без скидки. Поэтому скидку считают там же, где показывают
цену, а не в момент списания: иначе на витрине стояло бы одно число, а с
кошелька уходило другое.

**На рынке карта не ходит.** Из рук в руки передают наличные: рынок —
это стол, за которым лежит то, что можно взять руками. Перевод со счёта
на счёт для этого есть отдельно, в банке, и он идёт по номеру счёта, а не
через стол. В магазинах и конторах города карта работает везде.
"""

