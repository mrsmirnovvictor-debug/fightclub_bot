# ---------- скидки по карте ----------

# Скидка назначена местом, а не товаром: в одёжной лавке она одна на весь
# прилавок. Чего тут нет — там скидки нет вовсе, и это не забывчивость:
# мастерская, комиссионка и лавка мага картой платятся по полной цене.
DISCOUNTS: dict[Service, int] = {
    Service.CLOTHES: 10,
    Service.FAN: 10,
    Service.JEWEL: 10,
    Service.WEAPONS: 5,
    Service.POTIONS: 15,
    Service.HEAL: 10,
    Service.INSURANCE: 10,
    Service.TRAIN: 10,
}

# Где карта не ходит вовсе. Рынок — стол с наличными, и перевод со счёта
# на счёт для этого есть отдельно
CASH_ONLY: frozenset[Service] = frozenset({Service.TRADE})

CARD_BENEFITS: tuple[str, ...] = (
    "Скидка 10% в магазинах одежды, украшений и фанатской экипировки",
    "Скидка 5% в оружейных магазинах",
    "Скидка 15% в аптеке",
    "Скидка 10% на больницу, страховую и тренажёрный зал",
    "Оплата в магазинах и конторах города прямо со счёта",
    "Действует бессрочно: обслуживание 100 💰 в год, первый год бесплатно",
)

CARD_NOTE = (
    "Скидка считается по выбранному источнику оплаты: платишь картой — "
    "видишь цену со скидкой, платишь наличными — цену без неё."
)


def discount_of(service: Service | None) -> int:
    """Сколько процентов снимает карта в этом месте."""
    if service is None:
        return 0
    return DISCOUNTS.get(service, 0)


def card_works(service: Service | None) -> bool:
    """Ходит ли карта в этом месте."""
    return service not in CASH_ONLY


def with_discount(price: int, percent: int) -> int:
    """Цена со скидкой.

    Округляем вниз — в пользу бойца: на ста кредитах скидка в десять
    процентов даёт ровно девяносто, а на цене, которая на десять не
    делится, копейка достаётся бойцу, а не лавке. Обратное правило стоит
    в полисе, и там оно обратное намеренно: там скидка огромная, и
    копейка, отданная бойцу, делала бы её больше обещанной.

    Бесплатным по скидке не становится ничто: то, что стоило кредит,
    кредит и стоит. Иначе лавка раздавала бы дешёвый товар даром.
    """
    if price <= 0:
        return 0
    if percent <= 0:
        return price
    return max(1, price * (100 - percent) // 100)


def price_for(price: int, purse: str, service: Service | None) -> int:
    """Во что обойдётся эта цена из этого кошелька."""
    if purse != CARD:
        return price
    return with_discount(price, discount_of(service))


def saved_by_card(price: int, service: Service | None) -> int:
    """Сколько карта снимает с этой цены."""
    return max(0, price - price_for(price, CARD, service))


# ---------- номер счёта ----------

NUMBER_PREFIX = "VB"
NUMBER_GROUPS = 3
NUMBER_GROUP = 4


def make_number(rand: random.Random | None = None) -> str:
    """Новый номер счёта: «VB-1234-5678-9012».

    Номер разыгрывается, а не считается из бойца. Его называют вслух,
    чтобы принять перевод, — и по нему не должно читаться, кто его
    хозяин. Столкновение ловит база: номер уникален столбцом, и служба
    разыгрывает следующий.
    """
    dice = random.Random() if rand is None else rand
    groups = [
        f"{dice.randrange(10 ** NUMBER_GROUP):0{NUMBER_GROUP}d}"
        for _ in range(NUMBER_GROUPS)
    ]
    return "-".join([NUMBER_PREFIX, *groups])


def tidy_number(said: str) -> str:
    """Номер, набранный человеком, — к тому виду, в каком он лежит в базе.

    Пробелы, нижний регистр и потерянные дефисы — не ошибка бойца, а
    обычный способ переписать номер из чужого сообщения. Приводим к
    одному виду здесь, чтобы перевод не отказывал из-за пробела.
    """
    bare = "".join(said.split()).upper().replace("—", "-").replace("–", "-")
    bare = bare.replace("-", "")
    if bare.startswith(NUMBER_PREFIX):
        bare = bare[len(NUMBER_PREFIX):]
    if not bare.isdigit() or len(bare) != NUMBER_GROUPS * NUMBER_GROUP:
        return ""
    groups = [
        bare[at:at + NUMBER_GROUP]
        for at in range(0, len(bare), NUMBER_GROUP)
    ]
    return "-".join([NUMBER_PREFIX, *groups])


def card_number(number: str) -> str:
    """Номер карты: он же номер счёта. Карта привязана к нему одному.

    Второго номера у карты нет намеренно. Счёт и карта — одни деньги, и
    два разных номера на одни деньги означали бы, что боец должен помнить,
    какой из них называть.
    """
    return number


def year_text(paid_until: int) -> str:
    """До какого часа оплачено обслуживание — как это печатают на карте."""
    return club_moment(paid_until)


