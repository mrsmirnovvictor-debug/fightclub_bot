CASH = "cash"  # наличные: они же `player.credits`
CARD = "card"  # карта: деньги на счету

PURSES: tuple[str, ...] = (CASH, CARD)

PURSE_TITLES: dict[str, str] = {CASH: "Наличные", CARD: "Карта"}
PURSE_EMOJI: dict[str, str] = {CASH: "💰", CARD: "💳"}

