"""Рынок: правила обмена между бойцами.

Обмен — единственное место в клубе, где вещи и деньги переходят из рук в
руки без прилавка. Поэтому правил здесь больше про доверие, чем про
экономику.

**Приглашение живёт минуту.** Позвал — и ждёшь ответа; не ответили,
приглашение сгорело. Иначе «хочу меняться» висело бы на человеке
сутками.

**Правку видят оба, подтверждают оба.** Каждый складывает своё, чужую
половину трогать нельзя, а обмен проходит, только когда обе стороны
сказали «готов».

**Любая правка сбрасывает оба согласия.** Этого не просили, но без
этого обмен становится ловушкой: один подтверждает, второй подменяет
вещь на грош — и нажатие первого остаётся в силе. Согласие относится к
тому, что лежало на столе в момент нажатия, и ни к чему больше.

Комиссии нет: клуб в этом не участвует.
"""

from __future__ import annotations

# Сколько ждать ответа на приглашение
INVITE_SECONDS = 60

# Сколько вещей можно выложить с одной стороны
MAX_ITEMS = 4

# Брошенный обмен закрывается сам: две вкладки, открытые и забытые, иначе
# держали бы друг друга до перезапуска бота
IDLE_SECONDS = 10 * 60

# Клуб с обмена не берёт ничего
TRADE_FEE = 0

