"""Общежитие: комната студенту, пока он учится.

Третье жильё города и первое бесплатное. Квартиру снимают за деньги и
на месяц, камеру в тюрьме дают без спроса и на часы, а комнату в
общежитии дают **под учёбу**: записался на курс — есть где жить, кончил
учиться — комнату сдал.

**Платить не надо.** Общежитие при учебных домах, и живут в нём по
студенческому, а не по кошельку. Поэтому у комнаты нет ни цены, ни
срока в сутках: её срок — сама учёба.

**Права сюда не считаются.** Автошкола — не училище: там сдают билет за
один заход, а не ходят на занятия неделями (`bot/game/driving.py`).
Комнату дают тому, кто записан на курс, то есть учится в корпусе,
колледже, академии или университете.

**Вещи не пропадают.** Учёба кончилась — комната закрывается, но всё,
что в ней лежало, остаётся за хозяином: он приходит в общежитие и
забирает своё у администрации. Пока не забрал, новую комнату не дают —
иначе забытое копилось бы по всему дому.
"""

from __future__ import annotations

# Сколько вещей влезает в комнату. Четыре — это шкаф и полка над
# кроватью: общежитие не квартира, и кладовая в нём меньше самой малой
# однушки (шесть мест)
ROOM_SLOTS = 4

# Дом, в котором эти комнаты
DORM = "dormitory"


def room_number(taken: list[int]) -> int:
    """Номер свободной комнаты: наименьший из незанятых.

    Номер — не ключ, а имя: по нему комнату называют на экране. Берём
    наименьший свободный, чтобы номера не уезжали в тысячи, когда весь
    дом отучился и разъехался.
    """
    busy = set(taken)
    number = 1
    while number in busy:
        number += 1
    return number


def room_title(number: int) -> str:
    return f"комната №{number}"


def course_over(course: str, studying: str) -> bool:
    """Кончилась ли учёба, под которую давали комнату.

    Курс у бойца один, и бросить его можно только целиком: значит,
    «учится не тем» и «не учится вовсе» — одно и то же для комнаты.
    """
    return studying != course


