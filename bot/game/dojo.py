"""Школа боевых искусств: приём за дела в бою, а не за уровень.

Уровень даёт приём из трёх предложенных и даёт его сразу. Школа устроена
наоборот: в ней лежат все приёмы клуба, выбрать можно любой, но платить
за него надо не кредитами и не уровнем, а работой в бою — тем самым
действием, в котором приём и состоит.

**Приём копится своим делом.** Удар копится точными ударами, уворот —
уворотами, крит — критическими, блок с лечением — удержанными блоками.
Деление то же, что у энергии (`ENERGY_SOURCES`): класс силён тем, чем
кормится его шкала, и школа спрашивает ровно это. Поэтому воин, который
хочет уворот трикстера, учится уворачиваться, а не бить.

**Дела считаются во всех боях.** Дуэль, групповой, рейд, осада, драка в
подворотне — город не делит бои на зачётные и нет: удар остаётся ударом.

**Считается сделанное самим бойцом.** Уворот от «Проворности» и крит от
«Пролома» в зачёт не идут — ровно по тому же правилу, по которому они не
кормят энергию: приём себя не кормит. Иначе школа превращалась бы в
кольцо «приём учит приёму», и выучить второй было бы тем легче, чем
больше их уже есть.

**Цена приёма в школе — наименьшая возможная.** Приём, взятый на
развилке уровня, стоит по ступени этой развилки: «Сильный удар» на
третьем уровне стоит шесть энергии вместо трёх. Школа такого не берёт:
она учит приём на его собственной ступени, то есть по цене профильного
класса. Это и есть то, за что боец платит делами.

**Место под новый приём освобождает старый с той же ценой.** Слотов
четыре, ступеней тоже четыре, и у бойца, прошедшего свой путь, занято
всё. Поэтому приём из школы встаёт на место того, который стоил столько
же, — и забывается тот насовсем. Школа об этом говорит до начала учёбы, а
не после.

**В обучении один приём.** Записался на второй — первый брошен, и дела,
сделанные для него, не переносятся: учится тело, а не ведомость.
"""

from __future__ import annotations

from bot.game.abilities import TIER_COST, TIERS, Ability, Effect, Source
from bot.game.presence import plural

# Сколько дел нужно на приём каждой ступени. Растёт ровно: пятьсот за
# первую и дальше по пятьсот за каждую следующую
DEEDS: dict[int, int] = {1: 500, 3: 1000, 6: 1500, 10: 2000}

# Чей приём: эффект называет класс, которому он свойствен. Делёж тот же,
# что в `ENERGY_SOURCES`, и проверяется он классовыми приёмами — у
# каждого класса его стартовый приём обязан лежать в своей ветке
BRANCH: dict[Effect, str] = {
    Effect.DAMAGE: "warrior",
    Effect.DODGE: "rogue",
    Effect.COUNTER: "rogue",
    Effect.CRIT: "assassin",
    Effect.BREAK: "assassin",
    Effect.DOUBLE: "assassin",
    Effect.HEAL: "tank",
    Effect.PARRY: "tank",
}

# Ветки в том порядке, в каком они стоят на полке школы: сперва те, чем
# класс бьёт, потом чем уходит, потом чем выцеливает, потом чем держит
BRANCHES: tuple[str, ...] = ("warrior", "rogue", "assassin", "tank")

# Имя ветки в заголовке «Приёмы Воина». Родительный падеж — потому что
# по-русски заголовок иначе не читается, а падежей у класса в игре нет
BRANCH_TITLES: dict[str, str] = {
    "warrior": "Воина",
    "rogue": "Трикстера",
    "assassin": "Ассасина",
    "tank": "Танка",
}

# Каким делом копит каждая ветка
DEED_OF: dict[str, Source] = {
    "warrior": Source.HIT,
    "rogue": Source.DODGE,
    "assassin": Source.CRIT,
    "tank": Source.BLOCK,
}

# Как дело называется в строке ведомости «Точных ударов: 12»
DEED_TITLES: dict[Source, str] = {
    Source.HIT: "Точных ударов",
    Source.DODGE: "Уворотов",
    Source.CRIT: "Критических ударов",
    Source.BLOCK: "Успешных блоков",
}

# И как оно называется при числе: «нужно 500 точных ударов», «остался
# один уворот». Три формы, потому что по-русски их три
DEED_FORMS: dict[Source, tuple[str, str, str]] = {
    Source.HIT: ("точный удар", "точных удара", "точных ударов"),
    Source.DODGE: ("уворот", "уворота", "уворотов"),
    Source.CRIT: (
        "критический удар", "критических удара", "критических ударов",
    ),
    Source.BLOCK: ("успешный блок", "успешных блока", "успешных блоков"),
}


# И как его называют заданием: «нужно точно ударить 500 раз»
DEED_ACTS: dict[Source, str] = {
    Source.HIT: "точно ударить",
    Source.DODGE: "увернуться",
    Source.CRIT: "нанести критический удар",
    Source.BLOCK: "заблокировать удар",
}


def deed_name(source: Source, count: int) -> str:
    """Название дела при этом числе."""
    return plural(count, *DEED_FORMS[source])


def deed_act(source: Source) -> str:
    """Что надо делать, чтобы это дело копилось."""
    return DEED_ACTS[source]


def branch_of(ability: Ability) -> str:
    """Чей это приём: класс, которому он свойствен."""
    return BRANCH[ability.effect]


def deed_of(ability: Ability) -> Source:
    """Каким делом копится этот приём."""
    return DEED_OF[branch_of(ability)]


def needed(ability: Ability) -> int:
    """Сколько дел нужно на этот приём."""
    return DEEDS[ability.tier]


def price(ability: Ability) -> int:
    """Во сколько энергии приём встанет бойцу после школы.

    Наименьшая возможная цена: школа учит приём на его собственной
    ступени, а не на той, до которой дорос боец.
    """
    return TIER_COST[ability.tier]


def done(total: int, baseline: int, ability: Ability) -> int:
    """Сколько дел сделано для этого приёма. Выше нужного не растёт."""
    return max(0, min(needed(ability), total - baseline))


def ready(total: int, baseline: int, ability: Ability) -> bool:
    """Набрано ли на приём."""
    return total - baseline >= needed(ability)


