"""Экономика прогресса: опыт, уровни, апы, кредиты и рейтинг.

Все числа игрового баланса собраны здесь — чтобы крутить их, не трогая
логику боя и хендлеры.

**Лестница задана поимённо, а не формулой.** Раньше уровень стоил
«сто плюс пятьдесят за каждый прошедший», а ап — ровно четверть уровня,
и вся лестница умещалась в две строки. Умещалась, но и крутить её было
нечем: поднять цену девятого уровня, не тронув второй, формула не
давала. Теперь каждый ап назван числом — все пятьдесят шесть, — и
правка одного уровня ничего не значит для остальных.

Четвёртый ап по-прежнему совпадает с самим уровнем, и кредиты на нём
по-прежнему двойные: десять за ап и пятьдесят за уровень.
"""

from __future__ import annotations

import math

# ---------- уровни и опыт ----------

MAX_LEVEL = 15

# Промежуточные апы: четвёртый совпадает с получением уровня
MICRO_UPS_PER_LEVEL = 4
POINTS_PER_UP = 1

# Сколько опыта стоит каждый из четырёх апов уровня. Внутри уровня апы
# дорожают, и это нарочно: первый приходит скоро и держит бойца за
# столом, последний стоит дороже всего и совпадает с самим уровнем.
#
# Цена уровня — сумма его четвёрки. Пары уровней стоят одинаково
# (второй и третий, четвёртый и пятый, и так далее): лестница идёт
# ступенями по два, чтобы каждый второй уровень не был вдвое дороже
# предыдущего.
EXP_UPS: dict[int, tuple[int, int, int, int]] = {
    1: (100, 150, 200, 250),
    2: (300, 400, 500, 600),
    3: (300, 400, 500, 600),
    4: (600, 750, 900, 1_050),
    5: (600, 750, 900, 1_050),
    6: (1_000, 1_200, 1_400, 1_600),
    7: (1_000, 1_200, 1_400, 1_600),
    8: (1_500, 1_750, 2_000, 2_250),
    9: (1_500, 1_750, 2_000, 2_250),
    10: (2_100, 2_400, 2_700, 3_000),
    11: (2_100, 2_400, 2_700, 3_000),
    12: (3_200, 3_600, 4_000, 4_400),
    13: (3_200, 3_600, 4_000, 4_400),
    14: (3_200, 3_600, 4_000, 4_400),
}

# Базовый опыт за победу — столько боец получает за ровный бой с равным
# соперником. Всё остальное в формуле только множители к этому числу.
#
# Берётся он не по своему уровню, а по уровню старшего из бойцов: за
# победу над тем, кто выше, платят по его ставке. Прежде ту же работу
# делал отдельный множитель за разницу уровней, и считали опыт дважды —
# один раз по своему уровню, второй раз поправляя на чужой.
BASE_EXP: dict[int, int] = {
    1: 50,
    2: 100,
    3: 100,
    4: 150,
    5: 150,
    6: 200,
    7: 200,
    8: 250,
    9: 250,
    10: 300,
    11: 300,
    12: 400,
    13: 400,
    14: 400,
    15: 400,
}

# На сколько уровней вверх боец дотягивается за чужой ставкой. Без
# предела первый уровень брался бы двумя победами над бойцом
# двенадцатого — ставка 400 против своих 50, а весь уровень стоит 700, —
# и начало игры проходил бы не боец, а его старший знакомый.
LEVEL_REACH = 2

# Выше какого уровня вещей в городе нет. Прилавок кончается десяткой, и
# боссы одеваются по ней же: поздние уровни растят бойца, а не его
# снаряжение
GEAR_TOP_LEVEL = 10

# ---------- прибавка за урон ----------
#
# Отношение ХП: во сколько средних бойцов уложился нанесённый за бой
# урон. Считается по полным ХП, а не по тем, с которыми боец вышел на
# ринг: иначе побитый соперник стоил бы дешевле целого, и выгоднее было
# бы ждать, пока противник подлечится.
#
# В дуэли коридор узкий. Победа означает, что боец снял с соперника все
# его ХП, поэтому отношение упирается в сами ХП: пять процентов сверху
# достаются тому, чей соперник был крепче (его полные ХП выше моих в
# 1,105 раза и больше), и ничего — тому, кто бил слабейшего.
#
# В групповом бою коридор в десять раз шире, и там урон действительно
# решает: полтора базового достаётся тому, кто уложил полтора средних
# бойца, а не тому, кто простоял в блоке, пока отряд работал.
DUEL_DAMAGE_CAP = 1.05
GROUP_DAMAGE_CAP = 1.50

# ---------- антифарм ----------

# Доля награды за первый, второй, третий и последующие бои
# с одним и тем же соперником за сутки.
REPEAT_SHARES = (1.0, 0.8, 0.6, 0.5)
REPEAT_WINDOW_HOURS = 24

# Ручки на случай, если клуб начнёт выгорать: доля награды победителя,
# которая достанется проигравшему и участникам ничьей.
LOSS_EXP_SHARE = 0.0
DRAW_EXP_SHARE = 0.0

# ---------- кредиты ----------

# Кредиты капают только с роста бойца: за апы и за уровни. Сам бой денег не
# приносит — иначе доход считался бы не по времени в клубе, а по числу драк,
# и цены в лавке поплыли бы вслед за самым усидчивым.
UP_CREDITS = 10  # за каждый ап, включая тот, что совпал с уровнем
LEVEL_CREDITS = 50  # сверху за сам уровень

PRICE_RESPEC = 60
PRICE_CLASS_CHANGE = 200
PRICE_APPEARANCE = 20  # смена прозвища или аватара

# ---------- рейтинг ----------

RATING_START = 1000
RATING_BASE = 25
RATING_LEVEL_STEP = 0.2
RATING_MIN_DELTA = 5
RATING_MAX_DELTA = 60


def ups_of(level: int) -> tuple[int, ...]:
    """Четвёрка апов этого уровня. Пусто — уровень потолочный."""
    return EXP_UPS.get(level, ())


def exp_to_next_level(level: int) -> int:
    """Сколько опыта нужно, чтобы уйти с текущего уровня на следующий."""
    return sum(ups_of(level))


def exp_for_up(level: int, number: int) -> int:
    """Цена одного апа: `number` от 1 до четырёх. Ноль — такого апа нет."""
    ups = ups_of(level)
    if 1 <= number <= len(ups):
        return ups[number - 1]
    return 0


def exp_at_up(level: int, number: int) -> int:
    """Сколько опыта на уровне нужно накопить к апу номер `number`.

    Четвёртый ап стоит ровно столько же, сколько весь уровень: порог
    последнего апа и есть цена уровня. Отдельного числа для него нет —
    и не должно быть, иначе уровень и его четвёртый ап разошлись бы.
    """
    return sum(ups_of(level)[:max(0, number)])


def ups_earned(exp: int, level: int) -> int:
    """Сколько промежуточных апов заслужено накопленным на уровне опытом.

    Четвёртый сюда не идёт: его выдаёт сам уровень.
    """
    ups = ups_of(level)
    if not ups:
        return 0
    earned = 0
    for number in range(1, MICRO_UPS_PER_LEVEL):
        if exp >= exp_at_up(level, number):
            earned = number
    return earned


def credits_per_level() -> int:
    """Сколько кредитов приносит уровень — весь доход бойца, других нет.

    На это число смотрят цены в лавке: набор одной ступени стоит примерно
    втрое дороже — поэтому на всё сразу не хватает и приходится выбирать.
    """
    return MICRO_UPS_PER_LEVEL * UP_CREDITS + LEVEL_CREDITS


def base_level(my_level: int, rival_level: int) -> int:
    """По чьему уровню считать ставку: по старшему, но не выше чем на две.

    Ниже своего уровня ставка не падает никогда: за победу над младшим
    платят по своей, а не по его.
    """
    top = max(my_level, rival_level)
    return max(1, min(top, my_level + LEVEL_REACH, MAX_LEVEL))


def base_exp(level: int) -> int:
    """Ставка этого уровня."""
    if level <= 0:
        return BASE_EXP[1]
    return BASE_EXP.get(min(level, MAX_LEVEL), BASE_EXP[MAX_LEVEL])


def damage_share(
    damage_dealt: int, hp_total: int, fighters: int, group: bool = False
) -> float:
    """Отношение ХП: во сколько средних бойцов уложился нанесённый урон.

    Ниже единицы не опускается: за победу платят целую ставку, как бы
    мало крови боец ни пустил. Выше потолка не поднимается: иначе
    добивание впятером одного стоило бы как весь рейд.
    """
    mean = hp_total / max(1, fighters)
    cap = GROUP_DAMAGE_CAP if group else DUEL_DAMAGE_CAP
    if mean <= 0:
        return 1.0
    return max(1.0, min(cap, max(0, damage_dealt) / mean))


def repeat_share(previous_fights: int) -> float:
    """Во сколько раз урезать награду за повторный бой с тем же соперником."""
    if previous_fights < 0:
        previous_fights = 0
    if previous_fights >= len(REPEAT_SHARES):
        return REPEAT_SHARES[-1]
    return REPEAT_SHARES[previous_fights]


def win_exp(
    damage_dealt: int,
    my_level: int,
    rival_level: int,
    hp_total: int,
    fighters: int,
    group: bool = False,
    previous_fights: int = 0,
    exp_share: float = 1.0,
) -> int:
    """Опыт за победу: ставка старшего и три множителя к ней.

        ставка[старший, но не выше моего + 2]
            × отношение ХП
            × повторный бой
            × подписка

    Округление вверх — одно и в самом конце. Округлять по дороге значило
    бы, что опыт зависит от порядка умножений, а он от него зависеть не
    должен: подписчик получает полтора от того, что заработал, а не
    полтора от округлённого.
    """
    raw = (
        base_exp(base_level(my_level, rival_level))
        * damage_share(damage_dealt, hp_total, fighters, group)
        * repeat_share(previous_fights)
        * max(0.0, exp_share)
    )
    return max(1, math.ceil(raw))


def consolation_exp(winner_exp: int, share: float) -> int:
    """Утешительный опыт проигравшему или за ничью. По умолчанию — ноль."""
    if share <= 0:
        return 0
    return max(1, round(winner_exp * share))


def rating_delta(won: bool | None, my_level: int, opponent_level: int) -> int:
    """Изменение рейтинга: побить старшего дорого стоит, младшего — почти нет.

    `won=None` — ничья: рейтинг не двигается ни у кого. Раньше ничья шла
    поражением обоим, и двое равных бойцов, честно отбоксировавших шесть
    раундов, уходили с ринга беднее, чем пришли. За то, что никто не уступил,
    наказывать не за что.
    """
    if won is None:
        return 0
    difference = opponent_level - my_level if won else my_level - opponent_level
    raw = RATING_BASE * (1.0 + RATING_LEVEL_STEP * difference)
    delta = max(RATING_MIN_DELTA, min(RATING_MAX_DELTA, round(raw)))
    return delta if won else -delta


def apply_share(value: int, share: float) -> int:
    """Урезать награду, не обнуляя её полностью."""
    if value <= 0 or share >= 1.0:
        return value
    return max(1, round(value * share))
