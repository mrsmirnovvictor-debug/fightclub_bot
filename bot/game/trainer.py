"""Тренер — боец клуба, которого не существует.

Мини-рейд «Обучение кулачному бою»: в одиночных боях клуба всегда висит
заявка от Тренера, и принять её может только новичок — боец с первого по
четвёртый уровень. Дерётся Тренер сам, выбирая удары и блоки наугад, и
ничего, кроме опыта, за него не дают.

**Тренер выходит отражением ученика.** Его класс, уровень и
характеристики — те же, что у того, кто вышел против него. Поэтому бой
ровный: у обеих сторон одно и то же тело, тот же урон и тот же уворот, и
решает его только то, кто куда бил. Победа любого класса — половина
боёв, и это не подогнанное число, а устройство: симметричный бой другим
быть не может.

Прежде он выходил воином, заточенным под уворот и крит, на два уровня
старше ученика — и не работало это ни в одну сторону. Тело у него было
закреплено шестым уровнем, а развитый танк четвёртого уровня носит
вдвое больше здоровья: ученик брал в среднем 82 боя из ста, танк — все
сто. Свести такого воина к половине не выходит вовсе: одна и та же
заточка — еда для танка и стена для воина, разброс по классам тридцать
с лишним пунктов, и выравнивать его пришлось бы таблицей на каждую пару
«класс × уровень». Такая таблица держится до следующей правки классов, а
отражение — всегда.

Своё тело у Тренера всё-таки есть: по нему между боями затягивается
здоровье. Выходит он при этом с той же **долей** здоровья, что накопил,
а не с тем же числом единиц — иначе побитый Тренер против танка
выглядел бы целым, а целый против новичка — умирающим.
"""

from __future__ import annotations

import random

from bot.game.classes import ALL_ZONES, Stats, Zone, block_combo, get_class
from bot.game.reference import developed_stats

# Запись Тренера лежит в той же таблице, что и живые бойцы: так ему
# достаются и затягивание здоровья по часам клуба, и обычный ход боя,
# и ничего из этого не приходится писать заново. Идентификатор
# отрицательный — у Телеграма таких не бывает, и столкнуться с живым
# игроком он не может
TRAINER_ID = -1

TRAINER_NAME = "Тренер"

# Класс его собственной записи. В бою он не участвует: на ринг Тренер
# выходит в классе ученика. Нужен затем, что запись в таблице бойцов
# без класса не живёт
TRAINER_CLASS = "warrior"

# Линия образов в сцене боя. Своя, не классовая: у Тренера нарисован
# собственный комплект, и воином он выглядеть не должен — даже когда
# дерётся в классе ученика
TRAINER_ART = "master"

# Кого он учит. Выше четвёртого уровня учиться уже не у него
LEARNER_LEVELS = (1, 4)

# Уровень его собственного тела — того, по которому между боями
# затягивается здоровье. На бой оно не влияет: в бою тело берётся у
# ученика. Затягивание идёт долей запаса, а не числом единиц, поэтому
# размер этого тела не меняет и скорости лечения — только числа в логах
BODY_LEVEL = LEARNER_LEVELS[1] + 2

# Сколько опыта даёт победа над ним — по победам за сутки. Третья и
# дальше не дают ничего: Тренер учит, а не кормит
WIN_SHARES: tuple[float, ...] = (1.0, 0.5)


def may_learn(level: int) -> bool:
    """Пускают ли бойца этого уровня к Тренеру."""
    low, high = LEARNER_LEVELS
    return low <= level <= high


def body_stats() -> Stats:
    """Характеристики его собственной записи.

    Эталонная прокачка воина на `BODY_LEVEL`. Эти числа не выходят на
    ринг и видны только в журнале: в бою Тренер берёт характеристики
    ученика.
    """
    return developed_stats(get_class(TRAINER_CLASS), BODY_LEVEL)


def win_share(wins_today: int) -> float:
    """Какая доля опыта достанется за победу, если до неё их было столько.

    Первая победа за сутки — полный опыт, вторая — половина, дальше
    ничего. Сутки считаются календарные, по часам клуба.
    """
    if wins_today < len(WIN_SHARES):
        return WIN_SHARES[wins_today]
    return 0.0


def lesson_exp(full: int, wins_today: int) -> int:
    """Сколько опыта достанется за победу, если до неё их было столько.

    `full` — опыт, посчитанный обычной формулой клуба. Доля берётся по
    счёту побед за сутки, и третья победа даёт ровно ноль: тут не
    урезание награды, а её конец. Половина при этом не обнуляется —
    опыт за вторую победу есть всегда, пусть и мелкий.
    """
    share = win_share(wins_today)
    if share <= 0.0:
        return 0
    if share >= 1.0:
        return max(0, full)
    return max(1, round(full * share))


def trainer_moves(
    hands: int = 1, block_width: int = 2, rng: random.Random | None = None
) -> tuple[dict[int, Zone], tuple[Zone, ...]]:
    """Что Тренер делает в этом ходу: куда бьёт и чем закрывается.

    Наугад, и это не заглушка до лучшего ИИ. Предсказуемый соперник
    учит одному — своей привычке: разгадав её, ученик выносит Тренера
    вслепую и не узнаёт о бое ничего. Случайный заставляет смотреть на
    каждый ход заново, а это и есть то, чему тут учат. В ровном бою это
    к тому же единственное, чем бой вообще решается.

    `rng` — чтобы в проверках случайность была известной. В бою его не
    передают, и Тренер берёт общий генератор.
    """
    dice = rng or random
    attacks = {hand: dice.choice(ALL_ZONES) for hand in range(max(1, hands))}
    block = block_combo(dice.choice(ALL_ZONES), block_width)
    return attacks, block


