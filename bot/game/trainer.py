"""Тренер — боец клуба, которого не существует.

Мини-рейд «Обучение кулачному бою»: в одиночных боях клуба всегда висит
заявка от Тренера, и принять её может только новичок — боец с первого по
четвёртый уровень. Дерётся Тренер сам, выбирая удары и блоки наугад, и
ничего, кроме опыта, за него не дают.

Смысл его в том, чтобы новичку было с кем провести первый бой, когда
живого соперника в клубе нет. Поэтому он и не считается никуда: ни в
победы, ни в рейтинг, ни в ELO. Единственная награда — опыт, и тот
только за первые две победы в сутки.

Тело у Тренера одно на все бои: выносливость он не добирает с уровнем,
и запас здоровья у него поэтому постоянный. Растут только те
характеристики, которыми он дерётся, — иначе «здоровье восстановилось
до ста процентов» означало бы разное число в разных боях, и накопленное
между боями здоровье было бы не с чем сравнивать.
"""

from __future__ import annotations

from bot.game.classes import Stats, get_class
from bot.game.economy import MICRO_UPS_PER_LEVEL, POINTS_PER_UP

# Запись Тренера лежит в той же таблице, что и живые бойцы: так ему
# достаются и затягивание здоровья по часам клуба, и обычный ход боя,
# и ничего из этого не приходится писать заново. Идентификатор
# отрицательный — у Телеграма таких не бывает, и столкнуться с живым
# игроком он не может
TRAINER_ID = -1

TRAINER_NAME = "Тренер"

# Класс — воин: Тренер учит кулачному бою, а не трюкам. Заточка идёт
# не классом, а очками
TRAINER_CLASS = "warrior"

# Линия образов в сцене боя. Своя, не классовая: у Тренера нарисован
# собственный комплект, и воином он выглядеть не должен
TRAINER_ART = "master"

# Кого он учит. Выше четвёртого уровня учиться уже не у него
LEARNER_LEVELS = (1, 4)

# Насколько он сильнее того, кто вышел против него
LEVEL_GAP = 2

# Уровень, по которому собрано его тело. Выносливость берётся отсюда
# всегда, какой бы ни был соперник: запас здоровья у Тренера один на
# все бои, иначе «сто процентов здоровья» значило бы каждый раз другое
BODY_LEVEL = LEARNER_LEVELS[1] + LEVEL_GAP

# Сколько опыта даёт победа над ним — по победам за сутки. Третья и
# дальше не дают ничего: Тренер учит, а не кормит
WIN_SHARES: tuple[float, ...] = (1.0, 0.5)


def trainer_level(learner_level: int) -> int:
    """Каким уровнем Тренер выходит против этого бойца."""
    return learner_level + LEVEL_GAP


def may_learn(level: int) -> bool:
    """Пускают ли бойца этого уровня к Тренеру."""
    low, high = LEARNER_LEVELS
    return low <= level <= high


def win_share(wins_today: int) -> float:
    """Какая доля опыта достанется за победу, если до неё их было столько.

    Первая победа за сутки — полный опыт, вторая — половина, дальше
    ничего. Сутки считаются календарные, по часам клуба.
    """
    if wins_today < len(WIN_SHARES):
        return WIN_SHARES[wins_today]
    return 0.0


def trainer_stats(level: int) -> Stats:
    """Характеристики Тренера на этот уровень.

    Заточен под уворот и крит: три очка из четырёх уходят в проворство
    и интуицию. Но не все четыре — боец, не добравший ни силы, ни
    выносливости, оказывается слабее своего ученика, и учить ему
    нечему. Поэтому четвёртое очко идёт по очереди в силу и
    выносливость.

    Выносливость при этом всегда берётся по `BODY_LEVEL`: тело у
    Тренера одно, и меняются только те характеристики, которыми он
    дерётся.
    """
    base = get_class(TRAINER_CLASS).base_stats
    taken = _spend(level)
    return Stats(
        strength=base.strength + taken["strength"],
        agility=base.agility + taken["agility"],
        intuition=base.intuition + taken["intuition"],
        # Выносливость — всегда по телу, а не по уровню этого боя
        endurance=base.endurance + _spend(BODY_LEVEL)["endurance"],
    )


def _points(level: int) -> int:
    """Сколько очков боец этого уровня успел раздать."""
    return POINTS_PER_UP * MICRO_UPS_PER_LEVEL * max(0, level - 1)


# Куда уходит каждое следующее очко. Шесть из восьми — в проворство и
# интуицию поровну: заточка под уворот и крит, а не под один уворот.
# Оставшиеся два держат его в силе и в теле, иначе на четвёртом уровне
# ученик оказывается крепче учителя, и учить тому нечему
SPENDING: tuple[str, ...] = (
    "agility", "intuition", "agility", "strength",
    "intuition", "agility", "intuition", "endurance",
)


def _spend(level: int) -> dict[str, int]:
    """Раскладка очков этого уровня по характеристикам."""
    taken = {"strength": 0, "agility": 0, "intuition": 0, "endurance": 0}
    for number in range(_points(level)):
        taken[SPENDING[number % len(SPENDING)]] += 1
    return taken


