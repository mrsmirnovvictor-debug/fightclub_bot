"""Отряд: шесть бойцов, которых нанимают, растят и ставят на точки.

Это люди без аккаунта, но с карточкой: у них класс, уровень, опыт,
характеристики, рюкзак и надетые вещи. Поэтому в базе они лежат там же,
где игроки, — в `players`, только с отрицательным номером. Тем же
приёмом в городе живёт Тренер, и он же даёт отряду даром всё, что уже
написано про бойца: экипировку, износ, бой, лечение, травмы. Своя
таблица для бойца означала бы второй инвентарь, второй бой и второй
износ — и вечное «а в отряде это работает иначе».

**Хозяин у бойца один, и он же ему платит.** Шесть мест, и место
освобождается только увольнением или продажей. Наняться к двоим боец не
может: в `squad` на него одна строка.

**Характеристики боец себе не раздаёт.** Их считают по классу, уровню и
звёздности — и считают одинаково для всех, у кого эти три числа
совпали. Ни броска при найме, ни ручного распределения: иначе один и
тот же боец у двух игроков вышел бы разным, и объяснить это было бы
нечем.

**Апов у бойца нет, и очки своего уровня у него уже вложены.** Игрок
добирает их по три на уровень и до следующего ходит недокачанным, а
бойцу брать их нечем: раздачи у него не бывает. Поэтому первый уровень —
это старт и все три апа первого уровня, второй — всё то же плюс
четвёртый ап (сам уровень) и три апа второго. Иначе боец был бы слабее
одноуровневого игрока на три очка только потому, что у него нет руки,
которой очко берут. В шкале опыта у него по той же причине нет ни
засечек апгрейдов, ни их счёта.

**Звёздность — это не сила на старте, а скорость роста.** Все кандидаты
выходят первого уровня и первым уровнем одинаковы: 1⭐ и 5⭐ на витрине
различаются ценой и будущим, а не тем, что видно сейчас. Разница
копится уровнями, и к десятому она велика.

**В бой за хозяином идёт столько бойцов, сколько он взял** — от
одного до всего отряда. Выбор у каждого свой, и делает его хозяин в
карточке бойца: занятый точкой или больницей не идёт никуда. Опыт за
бой каждый получает свой, по своему уровню и своему урону.

**Спарринг идёт в счёт только бойцу.** Для него это бой: победа,
поражение или ничья записываются в его карточку. Хозяину — нет: своя
тренировка в статистику не идёт, как не идёт туда и урок у Тренера.

**Рейтинга у бойца нет.** ELO — место среди живых игроков, и боец в
этой лестнице не стоит: ни победа, ни поражение его не двигают, а в
карточке строки с рейтингом у него нет вовсе. Бои при этом считаются
как у человека: победы, поражения, ничьи и походы в подвал — его
собственный счёт, и он виден в карточке.

**Лицо у бойца своё.** То, которое стояло на витрине при найме, — и в
карточке, и в бою. Образа у него нет, и без этого правила картинку
подставлял бы класс: купленный боец оказывался бы другим человеком.

**Выше хозяина боец не растёт.** Опыт сверх потолка не сгорает, а
лежит: поднялся хозяин — боец догоняет. Иначе прокачанный отряд обгонял
бы владельца и дрался за него, а не с ним.

Цены и доли — здесь, действия — в `bot.squad_service`, экраны — в
`bot.webapp.squad`, имена и лица — в `bot.content.recruits`.
"""

from __future__ import annotations

import random

from bot.game.classes import START_POINTS, FighterClass, Stat, Stats
from bot.game.economy import MICRO_UPS_PER_LEVEL, win_exp
from bot.game.reference import FOCUS, developed_stats

# Сколько бойцов держит один хозяин. Шесть — это две полные тройки на
# точках города и всё ещё обозримая вкладка
SQUAD_LIMIT = 6

# Сколько кандидатов показывает витрина за раз
SHOWCASE_SIZE = 3

# Звёздность: от обычного бойца до того, ради кого копят
STARS: tuple[int, ...] = (1, 2, 3, 4, 5)

# Цена найма по звёздности. Разброс маленький нарочно: платят здесь не
# за силу сегодня, а за скорость роста, и пятикратная цена за будущее
# отрезала бы 5⭐ от всех, кроме богачей
HIRE_PRICE: dict[int, int] = {1: 300, 2: 350, 3: 400, 4: 450, 5: 500}

# С какой вероятностью выпадает звёздность. Доли в процентах и в сумме
# дают сотню; бросок идёт на каждого кандидата отдельно, поэтому три
# пятёрки подряд возможны — редки, но возможны
STAR_CHANCE: dict[int, int] = {1: 50, 2: 25, 3: 14, 4: 7, 5: 4}

# Сколько стоит посмотреть новых кандидатов, не дожидаясь недели. Цена
# растёт парами и к восьмому разу доходит до цены лучшего бойца: первый
# пересмотр — мелочь, восьмой — решение. Больше восьми за неделю нельзя
# вовсе, иначе витрина перестала бы быть ограничением для того, у кого
# много денег
REROLL_PRICES: tuple[int, ...] = (50, 50, 100, 100, 200, 200, 400, 400)
REROLL_LIMIT = len(REROLL_PRICES)


# Сколько спаррингов с хозяином в сутки идут бойцу в опыт и какой
# долей. Первый — полной, второй — половиной, третий и дальше — ничем:
# та же лестница, что у уроков Тренера, и по той же причине. Спарринг
# безопасен и бесплатен, и без убывающей доли отряд качался бы об
# хозяина круглые сутки, не выходя в город
SPAR_SHARES: tuple[float, ...] = (1.0, 0.5)
# Ставка спарринга считается по старшему из двоих, а не по уровню
# бойца: хозяин приводит на ринг себя, и бой с ним стоит столько,
# сколько стоит он. Иначе выходило бы, что десятый уровень учит первого
# даром — а это самый дорогой урок, какой боец может получить
SPAR_LESSONS = len(SPAR_SHARES)


def spar_share(done_today: int) -> float:
    """Какой долей идёт очередной спарринг этих суток."""
    if done_today < 0:
        done_today = 0
    if done_today >= len(SPAR_SHARES):
        return 0.0
    return SPAR_SHARES[done_today]


def spar_exp(full: int, done_today: int) -> int:
    """Опыт бойца за спарринг с хозяином.

    Ноль — занятий на сегодня хватит: третий бой подряд ничего не даёт
    и об этом сказано до боя, а не после.
    """
    share = spar_share(done_today)
    if share <= 0:
        return 0
    return max(1, int(round(full * share)))


def fight_exp(
    damage_dealt: int, level: int, rival_level: int, hp_total: int, fighters: int
) -> int:
    """Опыт бойца отряда за выигранный бой: ставка уровня и доля урона.

    Та же формула, по которой платят человеку в групповом бою, и это
    не совпадение: иначе отряд рос бы по отдельной лестнице, и
    объяснить разницу было бы нечем. Своя подписка у бойца не бывает,
    поэтому её множитель здесь всегда единица.

    Урон считается каждому свой: шестеро за одним хозяином получают
    по-разному, и получает больше тот, кто больше набил. Ниже целой
    ставки плата не падает — вышел и выиграл, значит заработал.
    """
    return win_exp(
        damage_dealt,
        max(1, level),
        max(1, rival_level),
        hp_total,
        fighters,
        group=True,
    )


def bonus_points(stars: int, level: int) -> int:
    """Сколько бонусных очков накопил боец этой звёздности к уровню.

    Бонус приходит с повышением, а не с рождением: на первом уровне его
    нет ни у кого, и витрина этим честна — там все одинаковы.

    По ступеням: 2⭐ получает очко на каждом третьем уровне (3, 6, 9…),
    3⭐ — на каждом втором (2, 4, 6…), 4⭐ — на каждом, начиная со
    второго, 5⭐ — по два на каждом. Обычный боец не получает ничего:
    он и есть мерка, относительно которой считают остальных.
    """
    if level < 2:
        return 0
    if stars <= 1:
        return 0
    if stars == 2:
        return level // 3
    if stars == 3:
        return level // 2
    if stars == 4:
        return level - 1
    return 2 * (level - 1)


def npc_stats(fclass: FighterClass, stars: int, level: int) -> Stats:
    """Характеристики бойца: всё, что даёт его уровень, плюс бонус звёзд.

    База — та же, по которой считают эталонного игрока: класс, уровень,
    очки за уровни. Бонус ложится в тот же круг вложений, которым класс
    качается с первого уровня, и продолжает его с того места, где он
    остановился. Поэтому 3⭐ ассасин — это не «ассасин с лишней силой»,
    а тот же ассасин, прошедший больше уровней.

    **Апов у бойца нет.** Игрок на своём уровне добирает очки
    апгрейдами — по три на уровень, — и до следующего уровня ходит
    недокачанным. У бойца раздавать их некому: своей воли у него нет, а
    хозяин распоряжается отрядом, не характеристиками. Поэтому боец
    стоит уже с вложенными очками своего уровня: первый уровень — это
    старт и все три апа первого уровня, второй — всё то же плюс
    четвёртый ап (сам уровень) и три апа второго. Иначе каждый боец был
    бы слабее одноуровневого игрока на три очка только потому, что ему
    нечем их взять.

    Ни одного броска: по классу, звёздности и уровню результат
    восстанавливается в любой момент, и база хранит только эти три
    числа вместо четырёх характеристик.
    """
    stats = developed_stats(fclass, level)
    plan = FOCUS[fclass.code]
    # Сколько шагов круга потратила база — с них и продолжаем
    spent = START_POINTS + MICRO_UPS_PER_LEVEL * (level - 1)
    # Промежуточные апы этого уровня у бойца уже вложены, а бонус звёзд
    # продолжает тот же круг сразу за ними
    extra = (MICRO_UPS_PER_LEVEL - 1) + bonus_points(stars, level)
    for step in range(extra):
        stats = stats.plus(Stat(plan[(spent + step) % len(plan)]))
    return stats


def hire_price(stars: int) -> int:
    """Во сколько обойдётся кандидат этой звёздности."""
    return HIRE_PRICE[stars]


def roll_stars(rng: random.Random | None = None) -> int:
    """Бросить звёздность кандидата по долям витрины."""
    dice = rng or random
    return dice.choices(STARS, weights=[STAR_CHANCE[one] for one in STARS])[0]


def reroll_price(done: int) -> int:
    """Цена следующего пересмотра витрины. Ноль — больше нельзя.

    `done` — сколько пересмотров уже куплено на этой неделе. Нулевой
    пересмотр (первый показ) бесплатен: он приходит сам с неделей.
    """
    if done < 0 or done >= REROLL_LIMIT:
        return 0
    return REROLL_PRICES[done]


def rerolls_left(done: int) -> int:
    """Сколько пересмотров осталось на этой неделе."""
    return max(0, REROLL_LIMIT - max(0, done))


def can_hold(squad_size: int) -> bool:
    """Есть ли куда взять ещё одного."""
    return squad_size < SQUAD_LIMIT


def capped_level(npc_level: int, owner_level: int) -> int:
    """Уровень бойца не выше хозяйского — и не ниже первого."""
    return max(1, min(npc_level, owner_level))


