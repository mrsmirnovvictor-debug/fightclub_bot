"""Ограбление: право мафии напасть на бойца прямо в доме.

Семья умеет брать территории — это война с городом. Ограбление — война
с человеком: мафиози видит, кто стоит рядом, и может взять его за
карман.

**Бьют по карману, а не по счёту.** Берут десятую часть наличных, и
только их: деньги на карте лежат в банке, а не при себе, и вынести их
из чужого кармана нельзя. Это и есть ответ на вопрос «зачем вообще
нужен счёт» — он был ответом на вопрос «зачем», а теперь стал ответом
на вопрос «от кого».

**Добыча идёт одному напавшему.** Помощники не получают ничего, и это
не скупость, а правило: иначе выгодно было бы собирать толпу на каждого
прохожего, и ограбление превратилось бы в охоту вшестером на одного за
полную цену.

**Нападение стоит лицензии.** Лицензии продают в особняке и только
своим. Одна лицензия — пачка на двадцать пять нападений, и срока у неё
нет: купил и ходи, пока не кончится. Потолка на покупку тоже нет —
потолок тут цена: за каждое нападение заплачено, и семья видит по
счётчику, кто сколько сделал.

**Вмешательство стоит той же лицензии.** Встал на чью-то сторону —
отдал своё право на нападение. Помощь не бесплатна ровно затем, чтобы
выбирать между «ограблю сам» и «помогу своему».

**Ограбленного не грабят снова.** После нападения у бойца шесть часов
покоя, кто бы ни победил. Без этого один мафиози держал бы одного
несчастного весь вечер, а пачка лицензий — это двадцать пять нападений,
а не двадцать пять нападений на одного.

**У семьи есть недельная цель.** Сделала столько нападений за неделю —
в сейф падает премия, одна на всех. Считаются нападения, доведённые до
развязки, а не начатые: иначе целью стало бы нажать кнопку.

Правил тут нет про сам бой: он идёт тем же движком, что дуэль, рейд и
штурм точки. Действия — в `bot.robbery_service`, хранение — в
`bot.database`, экраны — в `bot.webapp.crowd` и `bot.webapp.clans`.
"""

from __future__ import annotations

HOUR = 60 * 60

# Сколько стоит лицензия и на сколько нападений её хватает. Срока у неё
# нет: это пачка прав, а не абонемент на неделю. Лицензия тратится и на
# вмешательство тоже — встал на чью-то сторону, отдал своё право
LICENCE_PRICE = 100
ATTACKS_PER_LICENCE = 25

# Какую долю наличных уносит напавший. Десятая часть — чтобы ограбление
# было обидным, но не разорительным: на карте деньги целы, и ограбленный
# теряет то, что сам не унёс в банк
LOOT_SHARE = 0.10

# Сколько часов ограбленного не трогают, кто бы ни победил
SAFE_HOURS = 6
SAFE_SECONDS = SAFE_HOURS * HOUR

# Сколько бойцов может встать на одну сторону, считая самого
MAX_SIDE = 5

# Потолок раундов у драки свой не заводим: это тот же бой стенка на
# стенку, что и групповой, и судья у него тот же — `bot.game.battle`
# Сколько секунд у бойца на ход. Молчуна ведёт бросок: ограбление тем и
# отличается от дуэли, что жертву никто не спрашивал, готова ли она
TURN_SECONDS = 45

# Сколько нападений в неделю семья берёт целью и сколько за это падает
# в сейф. Цель общая: её закрывают все вместе, и премия тоже общая
WEEKLY_GOAL = 25
GOAL_REWARD = 5000


def loot_of(credits: int) -> int:
    """Сколько унесут из кармана. Меньше десятки не трогают вовсе."""
    return int(max(0, credits) * LOOT_SHARE)


def attacks_in(licences: int) -> int:
    """Сколько нападений даёт столько лицензий."""
    return max(0, licences) * ATTACKS_PER_LICENCE


def safe_left(robbed_at: int, now: int) -> int:
    """Сколько секунд бойца ещё не трогают. Ноль — можно нападать."""
    if not robbed_at:
        return 0
    return max(0, robbed_at + SAFE_SECONDS - now)


def goal_done(attacks: int) -> bool:
    """Закрыта ли недельная цель семьи."""
    return attacks >= WEEKLY_GOAL


def goal_left(attacks: int) -> int:
    """Сколько нападений осталось до премии."""
    return max(0, WEEKLY_GOAL - attacks)


