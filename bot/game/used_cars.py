"""Авторынок: цены на машины из рук в руки.

Комиссионка для вещей уже есть (`bot.game.market`), и правило там
простое: клуб берёт свою долю, а цену продавец ставит сам, но в рамках
прилавка. Здесь то же самое и для машин — вместе с долей клуба, чтобы
две торговые площадки города не расходились в том, сколько стоит
посредничество.

**Цену держим в рамках салона.** Дешевле половины салонной цены машина
уходила бы за бесценок второму своему же персонажу, дороже трёх цен —
превращала бы рынок в способ печатать кредиты из воздуха. Те же рамки,
что и у вещей: правило одно, и помнить его надо одно.

**На рынок выставляют только свою насовсем.** Снятая в салоне машина
бойцу не принадлежит — у неё свой срок и свой хозяин, — и продавать
чужое нельзя. Служебную тем более: её выдал гараж, а не кошелёк.

**Износа у машины нет, и в цене он не участвует.** Вещь продают с её
истрёпанностью, машину — как есть: других свойств, кроме скорости, у
неё не бывает (`docs/cars.md`).
"""

from __future__ import annotations

from bot.game.cars import Car
# Доля клуба и арифметика выплаты — общие с комиссионкой: посредничество
# в городе одно, и две разные доли читались бы как ошибка
from bot.game.market import FEE, fee_of, payout

# Во сколько раз цена может отличаться от салонной
MIN_SHARE = 0.5
MAX_SHARE = 3.0


def price_range(car: Car) -> tuple[int, int]:
    """Рамки цены для этой машины: от половины салонной до трёх."""
    return round(car.price * MIN_SHARE), round(car.price * MAX_SHARE)


def price_is_sane(car: Car, price: int) -> bool:
    """Влезает ли цена в рамки. Ноль и минус — не цена."""
    if price <= 0:
        return False
    low, high = price_range(car)
    return low <= price <= high


def price_hint(car: Car) -> str:
    """Подсказка продавцу — строкой, для витрины."""
    low, high = price_range(car)
    return f"от {low} до {high} 💰"


def sellable(car: Car) -> bool:
    """Можно ли такую машину вообще выставить.

    Служебную — нельзя: она принадлежит гаражу, а не бойцу. Про срок
    аренды здесь не спрашивают: это не свойство машины, а свойство той
    строки, что записана на бойца, и смотрит на неё служба.
    """
    return not car.service


