"""Что нового в клубе — то же самое, но словами игрока.

Здесь лежит список изменений, которые бот сам публикует в ветке новостей
группы. Правило одно: **никакой техники**. Игроку неинтересно, что где
переписано, — ему важно, что поменялось в бою, в лавке и на карточке.

Как это работает: каждая запись помечена своим кодом. Бот при запуске
сверяет коды с тем, что уже отправлял, и публикует только новое. Значит,
перезапуск ничего не задваивает, а чтобы объявить свежее изменение,
достаточно дописать сюда запись — код у неё должен быть новый.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Release:
    """Одно объявление в ветке новостей."""

    code: str  # стабильный ключ: по нему видно, что уже отправлено
    title: str
    lines: tuple[str, ...]
    footer: str = ""

    def render(self) -> str:
        parts = [f"📣 <b>{self.title}</b>", ""]
        parts += [f"• {line}" for line in self.lines]
        if self.footer:
            parts += ["", self.footer]
        return "\n".join(parts)


RELEASES: tuple[Release, ...] = (
    Release(
        code="2026-08-30-block-break",
        title="Крит пробивает блок",
        lines=(
            "Блок больше не спасает наверняка. Если удар должен был стать "
            "критическим, но упёрся в блок, он может этот блок проломить — "
            "и тогда проходит половина максимального урона.",
            "Обычный удар блок не пробивает никогда. Пробить может только крит.",
            "Держат блок все по-разному: крепче всех 🛡 танк, за ним ⚔️ воин, "
            "потом 🤸 трикстер, слабее всех 🗡 ассасин — он этот удар и наносит.",
            "Щит помогает удержать блок и под критом тоже.",
            "В карточке появилась строка «🛡🩸 Держит блок» — видно, насколько "
            "твоя защита готова к такому удару.",
            "В логе боя у пробития свой значок: 🛡🩸",
        ),
        footer="Проверить своё — /card. Подробности механики — /help.",
    ),
)


def by_code(code: str) -> Release | None:
    for release in RELEASES:
        if release.code == code:
            return release
    return None


__all__ = ["RELEASES", "Release", "by_code"]
