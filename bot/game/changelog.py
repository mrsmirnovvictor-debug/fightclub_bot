"""Что нового в клубе — то же самое, но словами игрока.

Здесь лежит список изменений, которые бот сам публикует в ветке новостей
группы. Правила два.

**Никакой техники.** Игроку неинтересно, что где переписано, — ему важно,
что поменялось в бою, в лавке и на карточке.

**Никаких команд.** Ветка новостей живёт в группе, а команды бота слушает
личка: «наберите /card» здесь просто не сработает, и человек решит, что
сломался бот.

Как это работает: каждая запись помечена своим кодом. Бот при запуске
сверяет коды с тем, что уже отправлял, и публикует только новое. Значит,
перезапуск ничего не задваивает, а чтобы объявить свежее изменение,
достаточно дописать сюда запись — код у неё должен быть новый.
"""

