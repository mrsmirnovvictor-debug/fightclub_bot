"""Наборы: во сколько работает оружие собранного комплекта.

У каждого набора есть своё оружие, и сила его зависит не от самого
оружия, а от того, сколько вещей этого же набора на бойце. Одна вещь —
просто оружие; собранный комплект — оружие, которое бьёт вполтора раза
сильнее.

**Лестница.** До трёх вещей набора оружие работает как написано, на
100%. С четвёртой — на 120%, с седьмой — на 135%, с девятой и дальше —
на 150%. Само оружие в этот счёт входит: надел его и ещё восемь вещей
набора — получил полтораста.

**Считаются вещи, а не слоты.** Кольцо у набора одно, а клеток под него
три, и носят их все три — значит, три вещи. Оружие можно взять и во
вторую руку: два одинаковых — две вещи. Так считает и сам боец, глядя на
куклу: сколько там вещей набора, столько и есть.

**Растёт всё, что оружие даёт.** Урон, прибавки к характеристикам, запас
здоровья и доли — точность, уворот, крит, антикрит, контрудар. Доля на
оружии и есть половина его силы, и оставить её в стороне значило бы, что
собранный комплект ассасина бьёт чаще, но мимо.

Потолки долей из лавки (`weapon_share_cap`) при этом не трогаются: они
про то, что написано на вещи в магазине, а не про то, во что её
превращает комплект. В бою доли всё равно упираются в боевые потолки —
`MAX_CRIT`, `MAX_DODGE` и остальные.

Числа и шаги здесь — решение владельца. Наборы, у которых вещей на
девятую ступень не хватает, дотянут позже: в них добавят предметов, а
лестница останется.
"""

from __future__ import annotations

from dataclasses import replace

from bot.game.gear import Item

# Сколько вещей набора надето → во сколько работает его оружие. Идёт
# сверху вниз: первая подошедшая ступень и есть ответ
SET_POWER_LADDER: tuple[tuple[int, float], ...] = (
    (9, 1.50),
    (7, 1.35),
    (4, 1.20),
)
# Оружие без комплекта работает как написано
BASE_POWER = 1.0

# Что в оружии растёт вместе с комплектом
AMPLIFIED_FLATS: tuple[str, ...] = (
    "damage_min",
    "damage_max",
    "hp",
    "strength",
    "agility",
    "intuition",
)
AMPLIFIED_SHARES: tuple[str, ...] = (
    "accuracy",
    "dodge",
    "crit",
    "anticrit",
    "counter",
)


def set_power(worn: int) -> float:
    """Во сколько работает оружие набора, если надето `worn` его вещей."""
    for need, power in SET_POWER_LADDER:
        if worn >= need:
            return power
    return BASE_POWER


def power_percent(power: float) -> int:
    """Та же сила, но процентами для экрана: 1.35 → 135."""
    return round(power * 100)


def next_step(worn: int) -> tuple[int, float] | None:
    """Следующая ступень: сколько вещей набора нужно и что она даст.

    None — боец уже на последней: дальше лестница не идёт.
    """
    better = [
        (need, power)
        for need, power in SET_POWER_LADDER
        if need > worn and power > set_power(worn)
    ]
    return min(better) if better else None


def amplified(item: Item, power: float) -> Item:
    """Оружие, как оно работает в собранном комплекте.

    Плоские числа округляются к ближайшему, а не вниз: на второй ступени
    120% от двойки — это 2.4, и вниз оно превратилось бы в ту же двойку,
    то есть комплект не дал бы ничего.

    Броню не трогаем: щит в наборе свой, и он не оружие, а у оружия
    брони не бывает вовсе.
    """
    if power == BASE_POWER:
        return item
    grown: dict[str, float] = {
        name: int(getattr(item, name) * power + 0.5) for name in AMPLIFIED_FLATS
    }
    grown.update(
        {
            name: round(getattr(item, name) * power, 4)
            for name in AMPLIFIED_SHARES
        }
    )
    return replace(item, **grown)


__all__ = [
    "AMPLIFIED_FLATS",
    "AMPLIFIED_SHARES",
    "BASE_POWER",
    "SET_POWER_LADDER",
    "amplified",
    "next_step",
    "power_percent",
    "set_power",
]
