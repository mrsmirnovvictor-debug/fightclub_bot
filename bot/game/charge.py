"""Заряд машины: сколько она ещё проедет и почём заряжают.

Машина в этом городе ездит не вечно. У неё есть запас хода в
километрах, и каждый километр дороги его тратит; кончился — боец
выходит и идёт пешком.

**Километр — это десять секунд пешком.** Ровно шаг города
(`locations.STEP`), и это не совпадение: расстояние между домами город
и так считает шагами, и заводить вторую меру длины значило бы держать
две правды об одном и том же. Отсюда и всё остальное: соседний дом —
два километра, дальний угол города — девять.

**Тратится расстояние, а не время за рулём.** Гиперкар проезжает те же
четыре километра в десять раз быстрее хэтчбека, но четыре километра
остаются четырьмя. Иначе быстрая машина ещё и тратила бы меньше, и
смысла в медленных не было бы вовсе.

**Хромота на расход не влияет.** Со сломанной ногой боец идёт дольше, а
проходит столько же: перелом удлиняет дорогу, а не город.

**Запас хода растёт вместе с классом.** Формула одна на всех: чем
быстрее машина, тем дальше она едет. Держать тринадцать чисел руками
значило бы однажды дать хэтчбеку больше, чем гиперкару, и не заметить.

**Заряд считается от пробега, а не хранится процентом.** В базе лежит
то, сколько машина проехала с последней зарядки; проценты — это взгляд
на это число. Так и точнее (процент целым числом терял бы километры), и
проще с теми машинами, что куплены до этого правила: пробег у них ноль,
то есть полный бак.
"""

from __future__ import annotations

from bot.game.cars import Car

# Километр города — тот же шаг, которым считается дорога
KM_SECONDS = 10

# Запас хода: сто двадцать километров всем плюс сорок за каждое деление
# скорости. Хэтчбек (×2) проходит 200, гиперкар (×10) — 520
BASE_RANGE = 120
RANGE_PER_TIMES = 40

# Насколько заряжает каждая из трёх колонок, в процентах
CHARGE_STEPS: tuple[int, ...] = (50, 75, 100)

# Сколько стоит и сколько идёт зарядка: процент к кредиту и процент к
# двенадцати секундам. Цена и время растут ровно с объёмом — колонка
# не торгуется, она наливает
CHARGE_PRICE_PER_PERCENT = 1
CHARGE_SECONDS_PER_PERCENT = 12

# Сколько машин заряжается разом. Колонок три, и они общие на город:
# очередь к зарядке — часть игры, а не недоделка
CHARGE_SLOTS = 3

# Станция стоит на АЗС
STATION = "gas_station"


def range_km(car: Car) -> int:
    """Сколько километров машина проходит на полном заряде."""
    return BASE_RANGE + RANGE_PER_TIMES * car.times


def km_for(walk_seconds: int) -> int:
    """Сколько километров в этой дороге. Считается по шагу пешком.

    Приходит сюда дорога без машины и без хромоты: и то и другое меняет
    время, а не расстояние.
    """
    if walk_seconds <= 0:
        return 0
    return max(1, round(walk_seconds / KM_SECONDS))


def percent_left(car: Car, driven: int) -> int:
    """Сколько процентов заряда осталось. Ноль — дальше пешком."""
    total = range_km(car)
    if total <= 0:  # pragma: no cover - машина без запаса хода
        return 0
    left = max(0, total - max(0, driven))
    return max(0, min(100, round(left * 100 / total)))


def km_left(car: Car, driven: int) -> int:
    """Сколько километров машина ещё проедет."""
    return max(0, range_km(car) - max(0, driven))


def empty(car: Car, driven: int) -> bool:
    """Кончился ли заряд: ехать больше нельзя."""
    return km_left(car, driven) <= 0


def after_drive(car: Car, driven: int, km: int) -> int:
    """Новый пробег после такой дороги. Дальше запаса не растёт."""
    return min(range_km(car), max(0, driven) + max(0, km))


def charge_price(percent: int) -> int:
    """Сколько стоит такая зарядка."""
    return max(0, percent) * CHARGE_PRICE_PER_PERCENT


def charge_seconds(percent: int) -> int:
    """Сколько она идёт."""
    return max(0, percent) * CHARGE_SECONDS_PER_PERCENT


def after_charge(car: Car, driven: int, percent: int) -> int:
    """Новый пробег после зарядки на столько процентов.

    Выше полного не заряжают: лишнее пропадает. Это и есть цена
    невнимательности — колонка наливает ровно столько, за сколько
    заплатили, а сверх полного баку деваться некуда.
    """
    total = range_km(car)
    added = round(total * max(0, percent) / 100)
    return max(0, min(total, max(0, driven) - added))


def wasted(car: Car, driven: int, percent: int) -> int:
    """Сколько процентов зарядки пропадёт впустую.

    Бак на семьдесят процентов и колонка на сто: тридцать нальются,
    семьдесят уйдут мимо. Колонка об этом говорит заранее — платить за
    пролитое, не зная, что оно прольётся, обидно.
    """
    missing = 100 - percent_left(car, driven)
    return max(0, max(0, percent) - missing)


