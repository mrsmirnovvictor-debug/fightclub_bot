"""Страховая компания: полис страхования жизни и здоровья.

Первая услуга страховой и первый документ в клубе. Полис не лечит и не
защищает от травмы — он делает лечение дешёвым: восемьдесят процентов
цены больница снимает по предъявлении полиса.

**Ровно месяц.** Не «до конца месяца» и не «тридцать суток с округлением»
— тридцать дней от часа оформления, час в час. Конец срока написан в самом
полисе, и по нему видно, до какой минуты он действует.

**Автопродление есть, и его можно выключить.** Включено — по истечении
срока полис продлевается сам, ещё на месяц и за те же деньги. Выключено —
кончается и лежит в документах просроченным, пока за ним не придут.

Продлевается полис **вперёд от конца срока, а не от сегодняшнего дня**, и
только один раз за подход. Боец, не заходивший в клуб полгода, не
обнаружит на счету шести списаний: клуб берёт деньги за услугу, а не за
время, в которое к услуге не приходили.

**Подписчику полис оформляют даром.** Это единственное, что PRO даёт из
услуг города, и цена здесь именно нулевая, а не сниженная: подписка и так
стоит звёзд.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import ceil

from bot.game.art import MAGIC
from bot.game.clock import club_moment

# Цена полиса: кредиты за месяц
POLICY_PRICE = 300

# Срок: ровно месяц, час в час
POLICY_DAYS = 30
DAY = 24 * 60 * 60
POLICY_SECONDS = POLICY_DAYS * DAY

# Сколько процентов цены лечения снимает полис
HEAL_DISCOUNT = 0.80

TITLE = "Полис страхования жизни и здоровья"
SHORT_TITLE = "Полис ЖиЗ"
EMOJI = "📄"
CODE = "life_health"
IMAGE = f"{MAGIC}/insurance_policy.jpeg"

# Страховщик: имя на бланке. Дом на карте зовётся «Страховая компания», а
# на самом полисе стоит название конторы — так документ читается документом
INSURER = "СК «Вегас-Гарант»"

COVERS = "Лечение любых травм в больнице города"

BENEFITS: tuple[str, ...] = (
    f"Скидка {round(HEAL_DISCOUNT * 100)}% на лечение любых травм в больнице",
    "Действует ровно месяц с часа оформления",
    "Автопродление — по желанию, выключается одной кнопкой",
)

NOTE = (
    "Полис покрывает только лечение травм. Перевязка и полное "
    "выздоровление — это здоровье, а не травма, и на них скидки нет."
)


def discounted(price: int) -> int:
    """Цена лечения по полису.

    Округляем вверх: на ста кредитах это ровно двадцать, а вот на цене,
    которая на пять не делится, копейка достаётся больнице, а не бойцу —
    иначе скидка была бы чуть больше обещанной.
    """
    if price <= 0:
        return 0
    return max(1, ceil(price * (1 - HEAL_DISCOUNT)))


def saved(price: int) -> int:
    """Сколько полис снимает с этой цены."""
    return max(0, price - discounted(price))


def policy_number(user_id: int, issued: int) -> str:
    """Номер полиса. Не хранится: он и так однозначен.

    Номер собирается из бойца и часа оформления, поэтому один и тот же
    полис всегда называется одинаково, а новый — иначе. Хранить его
    отдельным столбцом значило бы держать в базе то, что выводится из
    двух чисел, которые уже там лежат.
    """
    return f"ВГ-{user_id % 1_000_000:06d}-{club_moment(issued, '%y%m%d')}"


@dataclass(frozen=True)
class Policy:
    """Полис бойца: когда оформлен, до какого часа и продлевать ли."""

    issued: int
    until: int
    auto_renew: bool = True

    def is_active(self, now: int) -> bool:
        return now < self.until

    def seconds_left(self, now: int) -> int:
        return max(0, self.until - now)

    def due(self, now: int) -> bool:
        """Пора ли продлевать: срок вышел, а продление не выключали."""
        return self.auto_renew and not self.is_active(now)

    def renewed(self, now: int) -> "Policy":
        """Продлённый полис: месяц вперёд от конца срока.

        От конца, а не от «сейчас», — иначе продление съедало бы дни, и
        полис, за который заплатили месяц, жил бы меньше месяца. Но и не
        дальше, чем на месяц вперёд от сегодняшнего дня: за время, когда
        за услугой не приходили, клуб денег не берёт.
        """
        return Policy(
            issued=self.issued,
            until=max(self.until, now) + POLICY_SECONDS,
            auto_renew=True,
        )

    def period_text(self) -> str:
        """Период страхования — так, как он напечатан в документе."""
        return f"{club_moment(self.issued)} — {club_moment(self.until)}"


def fresh(now: int) -> Policy:
    """Новый полис на месяц от этого часа."""
    return Policy(issued=now, until=now + POLICY_SECONDS)


def extended(policy: Policy | None, now: int) -> Policy:
    """Полис после оплаты: новый или продлённый на месяц.

    Живой полис продлевается от своего конца — купивший второй месяц
    заранее получает два месяца, а не один. Просроченный начинается
    заново: числа в нём должны читаться как одна непрерывная история, а
    не как месяц, проведённый без страховки.
    """
    if policy is None or not policy.is_active(now):
        return fresh(now)
    return Policy(
        issued=policy.issued,
        until=policy.until + POLICY_SECONDS,
        auto_renew=policy.auto_renew,
    )


