"""Город как игрок: мэр и судья, которых никто не выбирал.

У города две должности, без которых он встаёт: **мэр** и **судья**.
Мэр назначает начальников, судья выносит приговоры. Если кресло
пустует, встаёт не правило, а сам город: некому назначить — значит,
никто не работает начальником; некому судить — значит, угон ничего не
стоит.

Поэтому обе должности у города есть всегда. Пока их занимают живые
люди — работают люди. Не занимают — работает город сам, и работает
скучно: по заявкам, по стажу и по лестнице, без любимчиков и без
настроения.

**Это не игроки.** Строк в `players` у них нет, и завести их значило
бы врать всем, кто считает город по людям: списку дома, бюллетеню,
рейтингу. У них есть только номер, имя и место, где они работают, —
этого хватает, чтобы подписать приговор и занять кресло мэра.

**Номера отрицательные.** Телеграм выдаёт только положительные, и
спутать городского судью с живым бойцом нельзя даже случайно.
"""

from __future__ import annotations

# Мэр от города: он же кандидат по умолчанию в каждых выборах
MAYOR_ID = -1
MAYOR_NAME = "Городская управа"
MAYOR_PROGRAM = (
    "Город работает и без мэра. Кресла начальников займут те, кто подал "
    "заявку и дольше работал, — по стажу, а не по знакомству."
)

# Судья от города: подписывает приговоры, пока мантию никто не надел
JUDGE_ID = -2
JUDGE_NAME = "Дежурный судья"

NAMES: dict[int, str] = {MAYOR_ID: MAYOR_NAME, JUDGE_ID: JUDGE_NAME}


def is_city(user_id: int) -> bool:
    """Это город, а не живой боец."""
    return int(user_id) in NAMES


def name_of(user_id: int) -> str:
    """Как зовут городского. Пусто — это не город."""
    return NAMES.get(int(user_id), "")


