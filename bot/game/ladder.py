"""Рейтинг недели: кто дрался, кто выше и кому за это платят.

Доска почёта клуба и рейтинг недели — разные списки, и путать их не
надо. Доска почёта — это все записанные, отсортированные по ELO: она
отвечает на вопрос «кто в городе сильнее». Рейтинг недели отвечает на
другой: «кто из сильных на этой неделе выходил на ринг». В нём только
те, кто провёл десять боёв, и каждое воскресенье за места в нём платят.

**Порог — десять боёв, и ровно десять уже хватает.** Порог нужен, чтобы
воскресную выплату нельзя было получить, ничего не делая: ELO остаётся
между неделями, и без порога деньги уходили бы тому, кто однажды
набрал рейтинг и с тех пор не дрался. Десять боёв — это вечер.

**Места считаются по общему ELO, а не по недельному приросту.** Так
просил заказчик, и это осознанный выбор: платят за то, что ты сильный
и играешь, а не за то, что на этой неделе удачно поднялся. Прирост
премировал бы новичка с двумя победами против чемпиона с ровным счётом.

**Неделя клуба — от воскресного полудня до воскресного полудня.** Та же
неделя, по которой живёт арена: границу держит `bot.game.clock`, и
здесь её не переопределяют. Принадлежность боя к неделе определяет
серверный миг, в который итог боя зафиксирован, — не время начала и не
часы на телефоне игрока. Бой, начатый в 11:58 воскресенья и кончившийся
в 12:01, целиком относится к новой неделе, и закрытый итог старой он не
трогает.

**Что считается боем.** Всё, что двигает ELO между живыми игроками:
дуэль в мини-аппе, дуэль в ветке группы, групповой бой и королевская
битва, бой турнирной арены. Бои с NPC, рейды и уличные нападения
рейтинг не двигают вовсе — поэтому их здесь и нет, и отдельного
запрета для них не нужно. Ничья — это бой, но не победа и не
поражение: она увеличивает счётчик боёв и не попадает ни в победы, ни
в поражения.

**Равенство разводится в четыре приёма, и все четыре нужны.** Сперва
ELO, потом победы недели (больше — выше), потом поражения недели
(меньше — выше), потом время, когда ELO стало текущим (раньше — выше).
Полное равенство всех четырёх разводит номер бойца: без него один и
тот же боец мог бы попасть на две страницы сразу или не попасть ни на
одну, потому что у SQLite нет обещания про порядок равных строк.

Места идут подряд, без пропусков и без общих мест: по призовой таблице
платят за место, и два первых места означали бы две первые премии.

Сам подсчёт и выплаты — в `bot.ladder_service`, экран — в
`bot.webapp.ladder`, журнал ELO — в таблице `rating_log`.
"""

from __future__ import annotations

from dataclasses import dataclass

from bot.game.clock import club_moment, week_closes, week_key, week_opens

# Сколько боёв за неделю нужно, чтобы попасть в рейтинг. Ровно десять
# уже хватает: «минимум десять» — это десять, а не одиннадцать
QUALIFY = 10

# Призовая таблица: до какого места включительно и сколько кредитов.
# Ступенями, а не строкой на место: иначе тридцать одна строка на
# диапазон «20–50» говорила бы ровно то же, что одна
PRIZE_STEPS: tuple[tuple[int, int], ...] = (
    (1, 400),
    (2, 375),
    (3, 350),
    (4, 300),
    (9, 200),
    (19, 100),
    (50, 50),
)

# Дальше пятидесятого не платят вовсе
PRIZE_NONE = 0


def prize_for(place: int) -> int:
    """Сколько кредитов за это место. Ниже пятидесятого — нисколько.

    Пустые места не оплачиваются и призы не перераспределяются: если
    порог прошли трое, они получат премии за первое, второе и третье, а
    деньги за остальные сорок семь мест просто не выйдут из кассы.
    """
    if place < 1:
        return PRIZE_NONE
    for last, prize in PRIZE_STEPS:
        if place <= last:
            return prize
    return PRIZE_NONE


def prize_table() -> list[dict[str, object]]:
    """Призовая таблица словами — для экрана и для объявления.

    Считается из тех же ступеней, по которым платят: таблица, набранная
    руками рядом с кодом выплаты, однажды разойдётся с ним.
    """
    rows: list[dict[str, object]] = []
    first = 1
    for last, prize in PRIZE_STEPS:
        rows.append(
            {
                "from": first,
                "to": last,
                "place": str(first) if first == last else f"{first}–{last}",
                "prize": prize,
            }
        )
        first = last + 1
    return rows


@dataclass(frozen=True)
class Standing:
    """Строка рейтинга недели: боец, его ELO и его неделя.

    `reached` — миг, в который ELO стало текущим (четвёртый ключ
    равенства). Ноль означает «держит с самого начала журнала»: такой
    боец стоит выше тех, кто поднялся позже, и это правда — его
    значение старше любой записи. Выдумывать ему дату мы не станем.
    """

    user_id: int
    rating: int
    fights: int
    wins: int
    losses: int
    reached: int = 0

    @property
    def qualified(self) -> bool:
        return self.fights >= QUALIFY

    @property
    def left(self) -> int:
        """Сколько боёв ещё не хватает до рейтинга. Ноль — хватает."""
        return max(0, QUALIFY - self.fights)

    def order_key(self) -> tuple[int, int, int, int, int]:
        """По чему сортируется строка. Меньше — выше место.

        Все четыре ключа согласованного порядка плюс номер бойца на
        самом дне. Знаки минус там, где «больше — выше»: сортировка
        одна и по возрастанию, а разворачивать её по каждому ключу
        отдельно в Python нельзя.
        """
        return (-self.rating, -self.wins, self.losses, self.reached, self.user_id)


def place_standings(rows: list[Standing]) -> list[tuple[int, Standing]]:
    """Расставить по местам: только прошедшие порог, места подряд.

    Непрошедшие отсеиваются до раздачи мест, а не после: иначе боец с
    девятью боями занял бы место и сдвинул всех, кто ниже.
    """
    ranked = sorted(
        (row for row in rows if row.qualified), key=lambda row: row.order_key()
    )
    return list(enumerate(ranked, start=1))


def progress_text(fights: int) -> str:
    """Личный прогресс до рейтинга: «7 из 10 PvP-боёв в клубе»."""
    return f"{min(fights, QUALIFY)} из {QUALIFY} PvP-боёв в Бойцовском клубе"


def period_text(moment: float) -> str:
    """Границы недели словами: «с 8 нояб. 12:00 до 15 нояб. 12:00»."""
    opened = club_moment(week_opens(moment), "%d.%m %H:%M")
    closed = club_moment(week_closes(moment), "%d.%m %H:%M")
    return f"с {opened} до {closed} по Москве"


def period_of(moment: float) -> str:
    """Ключ недели, в которую попадает этот миг."""
    return week_key(moment)


