"""Суд: наказание за угон и чем его платят.

Участок ловит, суд наказывает. Это не формальность: пока приговора нет,
у угонщика только отнятая машина, а штраф и срок назначает человек в
мантии — и назначает их по лестнице, а не по настроению.

**Лестница растёт.** Первый угон — штраф, второй — штраф и трое суток
решётки, третий и дальше — вчетверо больший штраф и шесть часов. Считаем
вынесенные приговоры, а не заведённые дела: наказывают за то, что
доказано, а не за то, в чём обвинили.

**Приговор выносят заочно.** Угонщик не обязан стоять в зале: судья
видит дело, видит, который это угон по счёту, и выносит. Исполняется
приговор, когда угонщик появится в городе, — до тех пор он просто
записан.

**Кресло судьи пустым не бывает.** Не назначили живого — дела ведёт
дежурный судья от города (`bot.game.city`), и ведёт их по той же
лестнице: человека в мантии город подменяет, а правила — нет.

**Деньги ищут по порядку.** Сперва карта: штраф — городское взыскание, и
берут его со счёта. Не хватило — счёт блокируют на остаток, и всё, что на
него придёт, уходит в долг. Счёта нет вовсе — берут наличными. Не хватило
и там — недоплата превращается в срок: час за каждые триста кредитов.

Правила здесь, действия — в `bot.court_service`, экран — в
`bot.webapp.court`.
"""

from __future__ import annotations

HOUR = 60 * 60

# Штраф за первый, второй, третий и всякий следующий угон
FINES: tuple[int, ...] = (300, 600, 1_200)

# Сколько часов решётки идёт вместе со штрафом. За первый угон срока
# нет: город даёт ошибиться один раз и заплатить за это деньгами
JAIL_HOURS: tuple[int, ...] = (0, 3, 6)

# Сколько кредитов недоплаты стоят часа решётки. Триста — цена первого
# угона: не заплатил самый дешёвый штраф, отсидел час
EXTRA_PER = 300


def step_of(times: int) -> int:
    """Какая это ступень лестницы. Первая — первый угон."""
    return max(1, min(times, len(FINES)))


def sentence_for(times: int) -> tuple[int, int]:
    """Штраф и часы решётки за `times`-й по счёту угон."""
    step = step_of(times)
    return FINES[step - 1], JAIL_HOURS[step - 1]


def extra_hours(unpaid: int) -> int:
    """Во сколько часов обходится недоплаченный штраф.

    Округляем вверх: сто кредитов долга — это час, а не треть часа.
    Часами город берёт то, чего не взял деньгами, и брать их долями
    было бы не наказанием, а бухгалтерией.
    """
    if unpaid <= 0:
        return 0
    return -(-unpaid // EXTRA_PER)


def sentence_text(fine: int, hours: int) -> str:
    """Приговор одной строкой — для экрана и для журнала."""
    if fine and hours:
        return f"{fine} 💰 и {hours} ч решётки"
    if fine:
        return f"{fine} 💰 штрафа"
    return f"{hours} ч решётки"


__all__ = [
    "EXTRA_PER",
    "FINES",
    "HOUR",
    "JAIL_HOURS",
    "extra_hours",
    "sentence_for",
    "sentence_text",
    "step_of",
]
