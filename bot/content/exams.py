def bank_of(topic: str) -> tuple[Question, ...]:
    """Все вопросы специальности. Пусто — такой специальности нет."""
    return EXAMS.get(topic, ())


def ticket(topic: str, user_id: int, tries: int, size: int) -> tuple[Question, ...]:
    """Билет на эту попытку: `size` вопросов из закромов.

    Считается, а не хранится. Зерно — боец и номер попытки, поэтому
    билет один и тот же, сколько раз его ни спроси, но на пересдаче уже
    другой. Хранить его негде: попытка живёт один запрос, а поле в базе
    под десяток номеров разошлось бы с показанным при первой же ошибке.
    """
    bank = list(bank_of(topic))
    if not bank:
        return ()
    if len(bank) <= size:
        return tuple(bank)
    Random(f"{topic}:{user_id}:{tries}").shuffle(bank)
    return tuple(bank[:size])


def grade(questions: tuple[Question, ...], chosen: list[int]) -> int:
    """Сколько верных. Лишние и недостающие ответы — неверные."""
    return sum(
        1
        for index, question in enumerate(questions)
        if index < len(chosen) and question.correct(chosen[index])
    )


