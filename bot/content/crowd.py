"""Кто стоит на улице: завсегдатаи города.

Город, по которому ходят ногами, пустует чаще, чем кажется: бойцов в
клубе немного, и застать кого-то в том же районе выходит не всегда. Улица
без единой живой души читается мертвее, чем список кнопок, — поэтому у
каждого размеченного района есть свои завсегдатаи.

Они ничего не умеют и ни на что не влияют: ни драться, ни торговать, ни
выдавать задания. Их дело — стоять и отвечать словом, когда к ним
подойдут. Как только за ними появится хоть одно правило, ему место в
`bot/game`, а не здесь: тут только содержимое.

Стоят они в долях от картинки района — тех же самых, что двери и пол.
Место выбирается так, чтобы человек оказался на улице, а не в стене:
проверяет это тест, а не глаз.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Local:
    """Завсегдатай: где стоит, как зовут и что говорит."""

    code: str
    name: str
    emoji: str
    # Доли от картинки района — как у дверей
    x: float
    y: float
    # Что скажет, если к нему подойти
    line: str


# Район → кто на нём стоит. Района нет в таблице — улица пустая, и это
# нормально: размечены под ходьбу пока не все
CROWD: dict[str, tuple[Local, ...]] = {
    "main_hub": (
        Local(
            code="doorman",
            name="Вышибала",
            emoji="🧍",
            x=0.60,
            y=0.44,
            line="Дерёшься — внутрь. Смотришь — с той стороны улицы.",
        ),
        Local(
            code="newsboy",
            name="Разносчик",
            emoji="🗞",
            x=0.40,
            y=0.86,
            line="В подвале опять шумели. Говорят, босс сменил стойку.",
        ),
        Local(
            code="mechanic",
            name="Механик",
            emoji="🔧",
            x=0.84,
            y=0.70,
            line="Железо чинят внутри. Я тут просто курю.",
        ),
    ),
}


def crowd_of(district: str) -> tuple[Local, ...]:
    """Кто стоит на этом районе. Пусто — улица без завсегдатаев."""
    return CROWD.get(district, ())


__all__ = ["CROWD", "Local", "crowd_of"]
