"""Имена и лица бойцов, которых нанимают в отряд.

Имя собирается из двух частей: имени и прозвища. Так зовут людей в
городе, где фамилию спрашивать не принято, а запоминают по тому, чем
человек известен: «Марко Отмычка», «Дэн Кирпич». Одно имя без прозвища
терялось бы среди шести бойцов отряда, а полное имя с фамилией звучало
бы как документ, а не как клуб.

**Пары не повторяются там, где их видят рядом.** Витрина из трёх и
отряд из шести — это девять имён на одном экране, и два «Марко
Отмычки» в них читались бы как ошибка. По городу повторы допустимы: у
соседа свой отряд, и пересечение там незаметно и неизбежно.

**Ни одного настоящего имени.** Ни знаменитостей, ни их узнаваемых
искажений: боец с именем живого человека — это чужое лицо в игре, где
оно ничего не значит.

Лица берутся из пула в бакете (`art.recruit_face`) и к классу не
привязаны: на карточке стоит обычный человек в городской одежде, а
класс он показывает в бою одной из четырёх моделей.
"""

from __future__ import annotations

import random

from bot.game.art import RECRUIT_FACES

# Имена. Город портовый и пёстрый, поэтому и список пёстрый: романские,
# славянские, тюркские, английские — вперемешку, как в настоящем
# городе, куда приезжают драться за деньги
NAMES: tuple[str, ...] = (
    "Марко", "Дэн", "Тео", "Рустам", "Арсен", "Лука", "Гор", "Ким",
    "Матео", "Борис", "Назар", "Эдди", "Самвел", "Осман", "Янис",
    "Фил", "Радж", "Тимур", "Леон", "Донат", "Карл", "Юсуф", "Гриша",
    "Нико", "Амир", "Влад", "Серж", "Ахмет", "Пьер", "Захар", "Томас",
    "Ильяс", "Витас", "Марат", "Айк", "Руди", "Жан", "Олаф", "Эмир",
    "Костас",
)

# Прозвища. Про ремесло, про повадку или про случай, после которого
# прилипло. Без боевых титулов вроде «Разрушителя»: такое имя обещает
# силу, которой у бойца первого уровня нет
NICKNAMES: tuple[str, ...] = (
    "Отмычка", "Кирпич", "Сквозняк", "Рубль", "Тихий", "Фонарь",
    "Наждак", "Пятка", "Пепел", "Шов", "Косой", "Пружина", "Клык",
    "Ржавый", "Шило", "Кочерга", "Бубен", "Турбина", "Лом", "Крот",
    "Сухой", "Якорь", "Гвоздь", "Фитиль", "Зяблик", "Обух", "Хрип",
    "Моляр", "Таран", "Пломба", "Двушка", "Кефир", "Шмель", "Валет",
    "Патрон", "Хомут", "Бидон", "Скрепка", "Сопля", "Уголь",
)


def all_pairs() -> int:
    """Сколько разных имён вообще умеет выдать город."""
    return len(NAMES) * len(NICKNAMES)


def make_name(
    taken: set[str] | None = None, rng: random.Random | None = None
) -> str:
    """Собрать имя, которого нет среди `taken`.

    Перебор идёт бросками, а не по списку: пар больше полутора тысяч, и
    занятых среди них девять в худшем случае. Если броски не нашли
    свободного имени за сто попыток — а это почти невозможно, — берём
    первое свободное по порядку, чтобы вызов не висел вечно.
    """
    dice = rng or random
    held = taken or set()
    for _ in range(100):
        name = f"{dice.choice(NAMES)} {dice.choice(NICKNAMES)}"
        if name not in held:
            return name
    for first in NAMES:
        for second in NICKNAMES:
            name = f"{first} {second}"
            if name not in held:
                return name
    # Пул кончился целиком — такого в городе не бывает, но пусть у
    # бойца будет хоть какое-то имя, а не пустая строка
    return f"{dice.choice(NAMES)} {dice.choice(NICKNAMES)}"


def pick_face(
    taken: set[int] | None = None, rng: random.Random | None = None
) -> int:
    """Выбрать лицо, которого нет среди `taken`. Номер от 1 до пула.

    Все тридцать два заняты — берём любое: отряд у соседа свой, и
    повтор лица там никому не мешает. Внутри одной витрины и одного
    отряда такого не случится: там мест меньше, чем лиц.
    """
    dice = rng or random
    free = [one for one in range(1, RECRUIT_FACES + 1) if one not in (taken or set())]
    return dice.choice(free or list(range(1, RECRUIT_FACES + 1)))


__all__ = ["NAMES", "NICKNAMES", "all_pairs", "make_name", "pick_face"]
