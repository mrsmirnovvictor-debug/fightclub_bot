@dataclass(frozen=True)
class Question:
    """Вопрос бармена: три ответа, один верный.

    `right` и `wrong` — то, что он скажет. Ошибка ничего не стоит и
    ничем не грозит: это разговор, а не экзамен, — поэтому в `wrong`
    стоит объяснение, а не упрёк, и попробовать можно снова.
    """

    text: str
    options: tuple[str, ...]
    answer: int
    right: str
    wrong: str


def _right(said: str) -> str:
    return f"«Верно. {said}»"


def _wrong(said: str) -> str:
    return f"«Не совсем. {said} Попробуй ещё раз»."


