def question(number: int) -> Question | None:
    """Вопрос билета по порядковому номеру с нуля. None — билет кончился."""
    return TICKET[number] if 0 <= number < len(TICKET) else None


def ask(number: int) -> dict:
    """Вопрос для страницы: без верного ответа и без пояснения.

    Отдаётся по одному: экзамен идёт вопрос за вопросом, и присылать
    наперёд то, чего боец ещё не видел, незачем — тем более что вместе с
    вопросами уехали бы и ответы.
    """
    one = TICKET[number]
    return {
        "number": number + 1,
        "total": len(TICKET),
        "text": one.text,
        "image": one.image,
        "options": list(one.options),
    }


