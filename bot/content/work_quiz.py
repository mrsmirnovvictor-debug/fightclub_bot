"""Мини-тест при приёме на работу: пять вопросов на каждую вакансию.

Вопросы про само ремесло, а не про клуб: бармена спрашивают о баре,
почтальона о почте. Это и есть смысл теста — на работу берут не за
уровень бойца, а за то, что он в ней понимает.

**Пять вопросов, четыре верных.** Восемьдесят процентов от пяти — это
ровно четыре: доля выбрана так, чтобы она делилась нацело и не
превращалась в спор об округлении. Ошибиться можно один раз.

**Правильный ответ не уезжает на страницу.** Наружу отдаются только
вопрос и варианты; сверяет ответы сервер. Иначе тест проходился бы
чтением ответа мини-аппа, и на работу брали бы за умение открыть
отладчик.

**Порядок вариантов не трогаем.** Перемешивать их на странице значило бы
раскладывать ответы по номерам, которых сервер не знает; перемешивать на
сервере — держать состояние попытки. Ни то, ни другое не нужно: вопросы
показываются один раз, и списать ответ неоткуда.
"""

