def quiz_for(code: str) -> tuple[Question, ...]:
    """Вопросы этой вакансии. Пусто — такой вакансии нет."""
    return QUIZZES.get(code, ())


def pass_mark(total: int, share: float) -> int:
    """Сколько верных ответов нужно, чтобы пройти.

    Округляем вверх: на пяти вопросах и доле в 0.8 это ровно четыре, но
    правило должно держаться и на другом числе вопросов — и держаться в
    пользу работодателя, а не соискателя.
    """
    from math import ceil

    return ceil(total * share)


def grade(code: str, chosen: list[int]) -> tuple[int, int]:
    """Сколько верных из скольких. Лишние и недостающие ответы — неверные."""
    questions = quiz_for(code)
    right = sum(
        1
        for index, question in enumerate(questions)
        if index < len(chosen) and question.correct(chosen[index])
    )
    return right, len(questions)


